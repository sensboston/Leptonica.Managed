    // leptonica: pixApplyVariableGrayMap (adaptmap.c)
    /// <summary>Maps an 8 bpp image pointwise so that the threshold given by a variable map becomes a constant.</summary>
    /// <param name="pixg">8 bpp, variable map</param>
    /// <param name="target">typ. 128 for threshold</param>
    /// <returns>pixd 8 bpp</returns>
    /// <remarks>
    /// (1) Suppose you have an image that you want to transform based
    ///     on some photometric measurement at each point, such as the
    ///     threshold value for binarization.  Representing the photometric
    ///     measurement as an image pixg, you can threshold in input image
    ///     using pixVarThresholdToBinary().  Alternatively, you can map
    ///     the input image pointwise so that the threshold over the
    ///     entire image becomes a constant, such as 128.  For example,
    ///     if a pixel in pixg is 150 and the target is 128, the
    ///     corresponding pixel in pixs is mapped linearly to a value
    ///     (128/150) of the input value.  If the resulting mapped image
    ///     pixd were then thresholded at 128, you would obtain the
    ///     same result as a direct binarization using pixg with
    ///     pixVarThresholdToBinary().
    /// (2) The sizes of pixs and pixg must be equal.
    /// </remarks>
    public Pix ApplyVariableGrayMap(Pix pixg, int target)
    {
        const string func = "pixApplyVariableGrayMap";
        int i, j, w, h, d, wpls, wplg, wpld, vals, valg, vald;
        byte[]? lut;
        float fval;
        Pix pixd;

        if (!SizesEqual(this, pixg))
            throw Lept.Arg(func, "pix sizes not equal");
        GetDimensions(out w, out h, out d);
        if (d != 8)
            throw Lept.Arg(func, "depth not 8 bpp");

            /* Generate a LUT for the mapping if the image is large enough
             * to warrant the overhead.  The LUT is of size 2^16.  For the
             * index to the table, get the MSB from pixs and the LSB from pixg.
             * Note: this LUT is bigger than the typical 32K L1 cache, so
             * we expect cache misses.  L2 latencies are about 5ns.  But
             * division is slooooow.  For large images, this function is about
             * 4x faster when using the LUT.  C'est la vie.  */
        lut = null;
        if (w * h > 100000) {  /* more pixels than 2^16 */
            lut = new byte[0x10000];
            for (i = 0; i < 256; i++) {
                for (j = 0; j < 256; j++) {
                    fval = (float)((float)(i * target) / (j + 0.5));
                    lut[(i << 8) + j] = (byte)Math.Min(255, (int)(fval + 0.5));
                }
            }
        }

        pixd = Create(w, h, 8);
        pixd.CopyResolution(this);
        uint[] datad = pixd.Data;
        wpld = pixd.Wpl;
        uint[] datas = Data;
        wpls = Wpl;
        uint[] datag = pixg.Data;
        wplg = pixg.Wpl;
        for (i = 0; i < h; i++) {
            ReadOnlySpan<uint> lines = datas.AsSpan(i * wpls, wpls);
            ReadOnlySpan<uint> lineg = datag.AsSpan(i * wplg, wplg);
            Span<uint> lined = datad.AsSpan(i * wpld, wpld);
            if (lut != null) {
                for (j = 0; j < w; j++) {
                    vals = GetDataByte(lines, j);
                    valg = GetDataByte(lineg, j);
                    vald = lut[(vals << 8) + valg];
                    SetDataByte(lined, j, vald);
                }
            }
            else {
                for (j = 0; j < w; j++) {
                    vals = GetDataByte(lines, j);
                    valg = GetDataByte(lineg, j);
                    fval = (float)((float)(vals * target) / (valg + 0.5));
                    vald = Math.Min(255, (int)(fval + 0.5));
                    SetDataByte(lined, j, vald);
                }
            }
        }

        return pixd;
    }

