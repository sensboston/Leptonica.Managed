    // leptonica: pixThresholdSpreadNorm (adaptmap.c)
    /// <summary>Adaptive threshold spread normalization; computes all three outputs.</summary>
    /// <param name="filtertype">L_SOBEL_EDGE or L_TWO_SIDED_EDGE</param>
    /// <param name="edgethresh">threshold on magnitude of edge filter; typ 10-20</param>
    /// <param name="smoothx">half-width of convolution kernel applied to
    ///                       spread threshold: use 0 for no smoothing</param>
    /// <param name="smoothy">half-height of convolution kernel applied to
    ///                       spread threshold: use 0 for no smoothing</param>
    /// <param name="gamma">gamma correction; typ. about 0.7</param>
    /// <param name="minval">input value that gives 0 for output; typ. -25</param>
    /// <param name="maxval">input value that gives 255 for output; typ. 255</param>
    /// <param name="targetthresh">target threshold for normalization</param>
    /// <param name="pixth">computed local threshold value</param>
    /// <param name="pixb">thresholded normalized image</param>
    /// <param name="pixd">normalized image</param>
    /// <remarks>
    /// (1) The basis of this approach is the use of seed spreading
    ///     on a (possibly) sparse set of estimates for the local threshold.
    ///     The resulting dense estimates are smoothed by convolution
    ///     and used to either threshold the input image or normalize it
    ///     with a local transformation that linearly maps the pixels so
    ///     that the local threshold estimate becomes constant over the
    ///     resulting image.  This approach is one of several that
    ///     have been suggested (and implemented) by Ray Smith.
    /// (2) You can use either the Sobel or TwoSided edge filters.
    ///     The results appear to be similar, using typical values
    ///     of edgethresh in the rang 10-20.
    /// (3) To skip the trc enhancement, use gamma = 1.0, minval = 0
    ///     and maxval = 255.
    /// (4) For the normalized image pixd, each pixel is linearly mapped
    ///     in such a way that the local threshold is equal to targetthresh.
    /// (5) The full width and height of the convolution kernel
    ///     are (2 * smoothx + 1) and (2 * smoothy + 1).
    /// (6) This function can be used with the pixtiling utility if the
    ///     images are too large.  See pixOtsuAdaptiveThreshold() for
    ///     an example of this.
    /// (7) In C, any of the three outputs can be NULL.  When pixd is
    ///     requested, pixb is the thresholded pixd; otherwise pixb is
    ///     made directly from pixs and the threshold array.  This call
    ///     asks for all three; use the overload with flags to ask for
    ///     a subset.
    /// </remarks>
    public void ThresholdSpreadNorm(int filtertype, int edgethresh, int smoothx, int smoothy,
                                    float gamma, int minval, int maxval, int targetthresh,
                                    out Pix pixth, out Pix pixb, out Pix pixd)
    {
        ThresholdSpreadNorm(filtertype, edgethresh, smoothx, smoothy, gamma, minval, maxval,
                            targetthresh, true, true, true,
                            out Pix? pth, out Pix? pb, out Pix? pd);
        pixth = pth!;
        pixb = pb!;
        pixd = pd!;
    }

    /// <summary>Adaptive threshold spread normalization with a choice of outputs.</summary>
    /// <param name="filtertype">L_SOBEL_EDGE or L_TWO_SIDED_EDGE</param>
    /// <param name="edgethresh">threshold on magnitude of edge filter; typ 10-20</param>
    /// <param name="smoothx">half-width of convolution kernel applied to
    ///                       spread threshold: use 0 for no smoothing</param>
    /// <param name="smoothy">half-height of convolution kernel applied to
    ///                       spread threshold: use 0 for no smoothing</param>
    /// <param name="gamma">gamma correction; typ. about 0.7</param>
    /// <param name="minval">input value that gives 0 for output; typ. -25</param>
    /// <param name="maxval">input value that gives 255 for output; typ. 255</param>
    /// <param name="targetthresh">target threshold for normalization</param>
    /// <param name="wantth">true if the computed local threshold array is wanted</param>
    /// <param name="wantb">true if the thresholded normalized image is wanted</param>
    /// <param name="wantd">true if the normalized image is wanted</param>
    /// <param name="pixth">computed local threshold value; null unless wantth</param>
    /// <param name="pixb">thresholded normalized image; null unless wantb</param>
    /// <param name="pixd">normalized image; null unless wantd</param>
    /// <remarks>
    /// See the version above for the notes.  If wantd is set, pixb is the
    /// result of thresholding pixd at targetthresh; if only wantb is set,
    /// it is pixVarThresholdToBinary() of this image with the threshold array.
    /// </remarks>
    public void ThresholdSpreadNorm(int filtertype, int edgethresh, int smoothx, int smoothy,
                                    float gamma, int minval, int maxval, int targetthresh,
                                    bool wantth, bool wantb, bool wantd,
                                    out Pix? pixth, out Pix? pixb, out Pix? pixd)
    {
        const string func = "pixThresholdSpreadNorm";
        Pix pixe, pixet, pixsd, pixg1, pixg2, pth;

        pixth = null;
        pixb = null;
        pixd = null;
        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (!wantth && !wantb && !wantd)
            throw Lept.Arg(func, "no output requested");
        if (filtertype != L.L_SOBEL_EDGE && filtertype != L.L_TWO_SIDED_EDGE)
            throw Lept.Arg(func, "invalid filter type");

            /* Get the thresholded edge pixels.  These are the ones
             * that have values in pixs near the local optimal fg/bg threshold. */
        if (filtertype == L.L_SOBEL_EDGE)
            pixe = SobelEdgeFilter(L.L_VERTICAL_EDGES);
        else  /* L_TWO_SIDED_EDGE */
            pixe = TwoSidedEdgeFilter(L.L_VERTICAL_EDGES);
        pixet = pixe.ThresholdToBinary(edgethresh);
        Invert(pixet, pixet);

            /* Build a seed image whose only nonzero values are those
             * values of pixs corresponding to pixels in the fg of pixet. */
        pixsd = CreateTemplate(this);
        pixsd.CombineMasked(this, pixet);

            /* Spread the seed and optionally smooth to reduce noise */
        pixg1 = pixsd.Seedspread(4);
        pixg2 = pixg1.Blockconv(smoothx, smoothy);

            /* Optionally do a gamma enhancement */
        pth = GammaTRC(null, pixg2, gamma, minval, maxval);

            /* Do the mapping and thresholding */
        if (wantd) {
            pixd = ApplyVariableGrayMap(pth, targetthresh);
            if (wantb)
                pixb = pixd.ThresholdToBinary(targetthresh);
        }
        else if (wantb)
            pixb = VarThresholdToBinary(pth);

        if (wantth)
            pixth = pth;
    }

