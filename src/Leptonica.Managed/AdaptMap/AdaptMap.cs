    // leptonica: pixBackgroundNormGrayArray (adaptmap.c)
    /// <summary>Makes the 16 bpp array of inverted background values of an 8 bpp image.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <param name="thresh">threshold for determining foreground</param>
    /// <param name="mincount">min threshold on counts in a tile</param>
    /// <param name="bgval">target bg val; typ. &gt; 128</param>
    /// <param name="smoothx">half-width of block convolution kernel width</param>
    /// <param name="smoothy">half-width of block convolution kernel height</param>
    /// <returns>16 bpp array of inverted background value</returns>
    /// <remarks>
    /// (1) See notes in pixBackgroundNorm().
    /// (2) This returns a 16 bpp pix that can be used by
    ///     pixApplyInvBackgroundGrayMap() to generate a normalized version
    ///     of the input pixs.
    /// </remarks>
    public Pix BackgroundNormGrayArray(Pix? pixim, int sx, int sy, int thresh, int mincount,
                                       int bgval, int smoothx, int smoothy)
    {
        const string func = "pixBackgroundNormGrayArray";
        bool allfg;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (pixim != null && pixim.Depth != 1)
            throw Lept.Arg(func, "pixim not 1 bpp");
        if (sx < 4 || sy < 4)
            throw Lept.Arg(func, "sx and sy must be >= 4");
        if (mincount > sx * sy) {
            Log.Warning(func, "mincount too large for tile size\n");
            mincount = (sx * sy) / 3;
        }

            /* If pixim exists, verify that it is not all foreground. */
        if (pixim != null) {
            Invert(pixim, pixim);
            allfg = pixim.Zero();
            Invert(pixim, pixim);
            if (allfg)
                throw Lept.Arg(func, "pixim all foreground");
        }

        Pix? pixm = GetBackgroundGrayMap(pixim, sx, sy, thresh, mincount);
        if (pixm == null)
            throw Lept.Fail(func, "pixm not made");
        Pix pixd = pixm.GetInvBackgroundMap(bgval, smoothx, smoothy);
        pixd.CopyResolution(this);
        return pixd;
    }

    // leptonica: pixBackgroundNormRGBArrays (adaptmap.c)
    /// <summary>Makes the three 16 bpp arrays of inverted background values of a 32 bpp image.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null</param>
    /// <param name="pixg">[optional] 8 bpp grayscale version; can be null</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <param name="thresh">threshold for determining foreground</param>
    /// <param name="mincount">min threshold on counts in a tile</param>
    /// <param name="bgval">target bg val; typ. &gt; 128</param>
    /// <param name="smoothx">half-width of block convolution kernel width</param>
    /// <param name="smoothy">half-width of block convolution kernel height</param>
    /// <param name="pixr">16 bpp array of inverted R background value</param>
    /// <param name="pixgr">16 bpp array of inverted G background value</param>
    /// <param name="pixb">16 bpp array of inverted B background value</param>
    /// <remarks>
    /// (1) See notes in pixBackgroundNorm().
    /// (2) This returns a set of three 16 bpp pix that can be used by
    ///     pixApplyInvBackgroundGrayMap() to generate a normalized version
    ///     of each component of the input pixs.
    /// </remarks>
    public void BackgroundNormRGBArrays(Pix? pixim, Pix? pixg, int sx, int sy, int thresh,
                                        int mincount, int bgval, int smoothx, int smoothy,
                                        out Pix pixr, out Pix pixgr, out Pix pixb)
    {
        const string func = "pixBackgroundNormRGBArrays";
        bool allfg;

        if (Depth != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
