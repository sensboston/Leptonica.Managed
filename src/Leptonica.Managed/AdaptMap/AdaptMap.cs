                    ReadOnlySpan<uint> mgLine = datamg.AsSpan(ti * wplmg, wplmg);
                    ReadOnlySpan<uint> mbLine = datamb.AsSpan(ti * wplmb, wplmb);
                    int sRow = y * wpls;
