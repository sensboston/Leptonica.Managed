    // leptonica: pixGetInvBackgroundMap (adaptmap.c)
    /// <summary>Makes the 16 bpp normalization image from an 8 bpp background map.</summary>
    /// <param name="bgval">target bg val; typ. &gt; 128</param>
    /// <param name="smoothx">half-width of block convolution kernel width</param>
    /// <param name="smoothy">half-width of block convolution kernel height</param>
    /// <returns>pixd 16 bpp</returns>
    /// <remarks>
    /// (1) bgval should typically be &gt; 120 and &lt; 240
    /// (2) pixd is a normalization image; the original image is
    ///   multiplied by pixd and the result is divided by 256.
    /// </remarks>
    public Pix GetInvBackgroundMap(int bgval, int smoothx, int smoothy)
    {
        const string func = "pixGetInvBackgroundMap";
        int w, h, wplsm, wpld, i, j;
        Pix pixsm, pixd;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs has colormap");
        GetDimensions(out w, out h, out _);
        if (w < 5 || h < 5)
            throw Lept.Arg(func, "w and h must be >= 5");

            /* smooth the map image */
        pixsm = Blockconv(smoothx, smoothy);
        uint[] datasm = pixsm.Data;
        wplsm = pixsm.Wpl;

            /* invert the map image, scaling up to preserve dynamic range */
        pixd = CreateNoInit(w, h, 16);
        uint[] datad = pixd.Data;
        wpld = pixd.Wpl;
        Span<ushort> invLut = stackalloc ushort[256];
        invLut[0] = (ushort)(bgval / 2);
        int num256 = 256 * bgval;
        for (int v = 1; v < 256; v++)
            invLut[v] = (ushort)(num256 / v);

        int w2 = w & ~1;
        bool hadZero = false;
        ref uint smRef = ref MemoryMarshal.GetArrayDataReference(datasm);
        ref uint dstRef = ref MemoryMarshal.GetArrayDataReference(datad);
        for (i = 0; i < h; i++) {
            ref uint linesmRef = ref Unsafe.Add(ref smRef, i * wplsm);
            ref uint linedRef = ref Unsafe.Add(ref dstRef, i * wpld);
            for (j = 0; j < w2; j += 2) {
                int v0 = GetDataByteUnchecked(ref linesmRef, j);
                int v1 = GetDataByteUnchecked(ref linesmRef, j + 1);
                if (v0 == 0 || v1 == 0) hadZero = true;
                Unsafe.Add(ref linedRef, j >> 1) = ((uint)invLut[v0] << 16) | invLut[v1];
            }
            if (j < w) {
                int v0 = GetDataByteUnchecked(ref linesmRef, j);
                if (v0 == 0) hadZero = true;
                Unsafe.Add(ref linedRef, j >> 1) = (uint)invLut[v0] << 16;
            }
        }
        if (hadZero)
            Log.Warning(func, "smoothed bg has 0 pixel!\n");

        pixd.CopyResolution(this);
        return pixd;
    }

