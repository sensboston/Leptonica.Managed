    /// <param name="factor">subsampling factor for getting average; &gt;= 1</param>
    /// <remarks>
    /// (1) The pixels in pixs corresponding to those in each
    ///     8-connected region in the mask are set to the average value.
    /// (2) This is required for adaptive mapping to avoid the
    ///     generation of stripes in the background map, due to
    ///     variations in the pixel values near the edges of mask regions.
    /// (3) This function is optimized for background smoothing, where
    ///     there are a relatively small number of components.  It will
    ///     be inefficient if used where there are many small components.
    /// </remarks>
    public void SmoothConnectedRegions(Pix? pixm, int factor)
    {
        const string func = "pixSmoothConnectedRegions";
        int i, n, x, y;
        bool empty;
        float aveval;
        Boxa boxa;
        Pix pixmc;
        Pixa pixa;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs has colormap");
        if (pixm == null) {
            Log.Info(func, "pixm not defined\n");
            return;
        }
        if (pixm.Depth != 1)
            throw Lept.Arg(func, "pixm not 1 bpp");
        empty = pixm.Zero();
        if (empty) {
            Log.Info(func, "pixm has no fg pixels; nothing to do\n");
            return;
        }

        boxa = pixm.ConnComp(out pixa, 8);
        n = boxa.Count;
        for (i = 0; i < n; i++) {
            pixmc = pixa.GetPix(i, L.L_CLONE);
            boxa.GetBoxGeometry(i, out x, out y, out _, out _);
            aveval = GetAverageMasked(pixmc, x, y, factor, L.L_MEAN_ABSVAL);
            PaintThroughMask(pixmc, x, y, (uint)(int)aveval);
        }
    }

