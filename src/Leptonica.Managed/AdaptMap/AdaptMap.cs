    // leptonica: pixApplyInvBackgroundGrayMap (adaptmap.c)
    /// <summary>Applies the 16 bpp inverse background map to an 8 bpp image.</summary>
    /// <param name="pixm">16 bpp, inverse background map</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <returns>pixd 8 bpp</returns>
    public Pix ApplyInvBackgroundGrayMap(Pix pixm, int sx, int sy)
    {
        const string func = "pixApplyInvBackgroundGrayMap";

        if (Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs has colormap");
        if (pixm.Depth != 16)
            throw Lept.Arg(func, "pixm undefined or not 16 bpp");
        if (sx == 0 || sy == 0)
            throw Lept.Arg(func, "invalid sx and/or sy");

        uint[] datas = Data;
        int wpls = Wpl;
        GetDimensions(out int w, out int h, out _);
        pixm.GetDimensions(out int wm, out int hm, out _);
        int wCov = sx > 0 ? Math.Min(w, wm * sx) : 0;
        int hCov = sy > 0 ? Math.Min(h, hm * sy) : 0;
        Pix pixd = (wCov == w && hCov == h) ? CreateTemplateNoInit(this) : CreateTemplate(this);
        uint[] datad = pixd.Data;
        int wpld = pixd.Wpl;
        uint[] datam = pixm.Data;
        int wplm = pixm.Wpl;

        if (wCov > 0 && hCov > 0) {
            LeptParallel.ForRows(hCov, wCov, (yStart, yEnd) => {
                ref uint datasRef = ref MemoryMarshal.GetArrayDataReference(datas);
                ref uint datadRef = ref MemoryMarshal.GetArrayDataReference(datad);
                for (int y = yStart; y < yEnd; y++) {
                    int ti = y / sy;
                    ReadOnlySpan<uint> mLine = datam.AsSpan(ti * wplm, wplm);
                    ref uint srcLineRef = ref Unsafe.Add(ref datasRef, y * wpls);
                    ref uint dstLineRef = ref Unsafe.Add(ref datadRef, y * wpld);
                    if (wCov == w && (w & 3) != 0)
                        Unsafe.Add(ref dstLineRef, w >> 2) = 0;
                    for (int j = 0; j < wm; j++) {
                        int x0 = j * sx;
                        if (x0 >= wCov) break;
                        int x1 = Math.Min(x0 + sx, wCov);
                        uint val16 = (uint)GetDataTwoBytes(mLine, j);
                        for (int x = x0; x < x1; x++) {
                            uint vals = (uint)GetDataByteUnchecked(ref srcLineRef, x);
                            uint vald = (vals * val16) >> 8;
                            if (vald > 255u) vald = 255u;
                            SetDataByteUnchecked(ref dstLineRef, x, (int)vald);
                        }
                    }
                }
            });
        }

        return pixd;
    }

