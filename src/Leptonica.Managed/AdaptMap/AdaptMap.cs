        int wpls = Wpl;
        int w = Width;
        int h = Height;
        int wm = pixmr.Width;
        int hm = pixmr.Height;
        int wCov = sx > 0 ? Math.Min(w, wm * sx) : 0;
        int hCov = sy > 0 ? Math.Min(h, hm * sy) : 0;
