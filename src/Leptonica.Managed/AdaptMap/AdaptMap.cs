    // leptonica: pixBackgroundNorm (adaptmap.c)
    /// <summary>Normalizes the image intensity so that the background is near bgval.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null</param>
    /// <param name="pixg">[optional] 8 bpp grayscale version; can be null</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <param name="thresh">threshold for determining foreground</param>
    /// <param name="mincount">min threshold on counts in a tile</param>
    /// <param name="bgval">target bg val; typ. &gt; 128</param>
    /// <param name="smoothx">half-width of block convolution kernel width</param>
    /// <param name="smoothy">half-width of block convolution kernel height</param>
    /// <returns>pixd 8 bpp or 32 bpp rgb</returns>
    /// <remarks>
    /// (1) This is a top-level interface for normalizing the image intensity
    ///     by mapping the image so that the background is near the input
    ///     value %bgval.
    /// (2) The input image is either grayscale or rgb.
    /// (3) For each component in the input image, the background value
    ///     in each tile is estimated using the values in the tile that
    ///     are not part of the foreground, where the foreground is
    ///     determined by %thresh.
    /// (4) An optional binary mask can be specified, with the foreground
    ///     pixels typically over image regions.  The resulting background
    ///     map values will be determined by surrounding pixels that are
    ///     not under the mask foreground.  The origin (0,0) of this mask
    ///     is assumed to be aligned with the origin of the input image.
    ///     This binary mask must not fully cover pixs, because then there
    ///     will be no pixels in the input image available to compute
    ///     the background.
    /// (5) An optional grayscale version of the input pixs can be supplied.
    ///     The only reason to do this is if the input is RGB and this
    ///     grayscale version can be used elsewhere.  If the input is RGB
    ///     and this is not supplied, it is made internally using only
    ///     the green component, and destroyed after use.
    /// (6) The dimensions of the pixel tile (%sx, %sy) give the amount
    ///     by which the map is reduced in size from the input image.
    /// (7) The input image is binarized using %thresh, in order to
    ///     locate the foreground components.  If this is set too low,
    ///     some actual foreground may be used to determine the maps;
    ///     if set too high, there may not be enough background
    ///     to determine the map values accurately.  Typically, it is
    ///     better to err by setting the threshold too high.
    /// (8) A %mincount threshold is a minimum count of pixels in a
    ///     tile for which a background reading is made, in order for that
    ///     pixel in the map to be valid.  This number should perhaps be
    ///     at least 1/3 the size of the tile.
    /// (9) A %bgval target background value for the normalized image.  This
    ///     should be at least 128.  If set too close to 255, some
    ///     clipping will occur in the result.  It is recommended to use
    ///     %bgval = 200.
    /// (10) Two factors, %smoothx and %smoothy, are input for smoothing
    ///      the map.  Each low-pass filter kernel dimension is
    ///      is 2 * (smoothing factor) + 1, so a
    ///      value of 0 means no smoothing. A value of 1 or 2 is recommended.
    /// (11) See pixCleanBackgroundToWhite().  The recommended value for %bgval
    ///      is 200.  As done there, pixBackgroundNorm() is typically followed
    ///      by pixGammaTRC(), where the maxval must not not exceed %bgval.
    /// </remarks>
    public Pix BackgroundNorm(Pix? pixim, Pix? pixg, int sx, int sy, int thresh, int mincount,
                              int bgval, int smoothx, int smoothy)
    {
        const string func = "pixBackgroundNorm";
        bool allfg;
        Pix? pixm, pixmi, pixd;

        int d = Depth;
        if (d != 8 && d != 32)
            throw Lept.Arg(func, "pixs not 8 or 32 bpp");
        if (sx < 4 || sy < 4)
            throw Lept.Arg(func, "sx and sy must be >= 4");
        if (mincount > sx * sy) {
            Log.Warning(func, "mincount too large for tile size\n");
            mincount = (sx * sy) / 3;
        }

            /* If pixim exists, verify that it is not all foreground. */
        if (pixim != null) {
            Invert(pixim, pixim);
            allfg = pixim.Zero();
            Invert(pixim, pixim);
            if (allfg)
                throw Lept.Arg(func, "pixim all foreground");
        }

        pixd = null;
        if (d == 8) {
                /* In C the map getters return an error code with a NULL map
                 * for invalid input; here they throw, so catch that case. */
            try {
                pixm = GetBackgroundGrayMap(pixim, sx, sy, thresh, mincount);
            } catch (ArgumentException) {
                pixm = null;
            }
            if (pixm == null) {
                Log.Warning(func, "map not made; return a copy of the source\n");
                return Copy(null, this);
            }

            try {
                pixmi = pixm.GetInvBackgroundMap(bgval, smoothx, smoothy);
            } catch (ArgumentException) {
                pixmi = null;
            }
            if (pixmi == null) {
                Log.Warning(func, "pixmi not made; return a copy of source\n");
                return Copy(null, this);
            } else {
                pixd = ApplyInvBackgroundGrayMap(pixmi, sx, sy);
            }
        }
        else {
            bool ok;
            Pix? pixmr, pixmg, pixmb;
            try {
                ok = GetBackgroundRGBMap(pixim, pixg, sx, sy, thresh,
                                         mincount, out pixmr, out pixmg, out pixmb);
            } catch (ArgumentException) {
                ok = false;
                pixmr = pixmg = pixmb = null;
            }
            if (!ok || pixmr == null || pixmg == null || pixmb == null) {
                Log.Warning(func, "map not made; return a copy of the source\n");
                return Copy(null, this);
            }

            Pix? pixmri = TryGetInvBackgroundMap(pixmr, bgval, smoothx, smoothy);
            Pix? pixmgi = TryGetInvBackgroundMap(pixmg, bgval, smoothx, smoothy);
            Pix? pixmbi = TryGetInvBackgroundMap(pixmb, bgval, smoothx, smoothy);
            if (pixmri == null || pixmgi == null || pixmbi == null) {
                Log.Warning(func, "not all pixm*i are made; return src copy\n");
                pixd = Copy(null, this);
            } else {
                pixd = ApplyInvBackgroundRGBMap(pixmri, pixmgi, pixmbi, sx, sy);
            }
        }

        pixd.CopyResolution(this);
        return pixd;
    }

        /* pixGetInvBackgroundMap() returns NULL on invalid input in C. */
    private static Pix? TryGetInvBackgroundMap(Pix pixs, int bgval, int smoothx, int smoothy)
    {
        try {
            return pixs.GetInvBackgroundMap(bgval, smoothx, smoothy);
        } catch (ArgumentException) {
            return null;
        }
    }

    // leptonica: pixBackgroundNormMorph (adaptmap.c)
    /// <summary>Normalizes the image intensity, estimating the background by a grayscale closing.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null</param>
    /// <param name="reduction">at which morph closings are done; between 2 and 16</param>
    /// <param name="size">of square Sel for the closing; use an odd number</param>
    /// <param name="bgval">target bg val; typ. &gt; 128</param>
    /// <returns>pixd 8 bpp or 32 bpp rgb</returns>
    /// <remarks>
    /// (1) This is a top-level interface for normalizing the image intensity
    ///     by mapping the image so that the background is near the input
    ///     value 'bgval'.
    /// (2) The input image is either grayscale or rgb.
    /// (3) For each component in the input image, the background value
    ///     is estimated using a grayscale closing; hence the 'Morph'
    ///     in the function name.
    /// (4) An optional binary mask can be specified, with the foreground
    ///     pixels typically over image regions.  The resulting background
    ///     map values will be determined by surrounding pixels that are
    ///     not under the mask foreground.  The origin (0,0) of this mask
    ///     is assumed to be aligned with the origin of the input image.
    ///     This binary mask must not fully cover pixs, because then there
    ///     will be no pixels in the input image available to compute
    ///     the background.
    /// (5) The map is computed at reduced size (given by 'reduction')
    ///     from the input pixs and optional pixim.  At this scale,
    ///     pixs is closed to remove the background, using a square Sel
    ///     of odd dimension.  The product of reduction * size should be
    ///     large enough to remove most of the text foreground.
    /// (6) No convolutional smoothing needs to be done on the map before
    ///     inverting it.
    /// (7) A 'bgval' target background value for the normalized image.  This
    ///     should be at least 128.  If set too close to 255, some
    ///     clipping will occur in the result.
    /// </remarks>
    public Pix BackgroundNormMorph(Pix? pixim, int reduction, int size, int bgval)
    {
        const string func = "pixBackgroundNormMorph";
        bool allfg;
        Pix? pixd;

        int d = Depth;
        if (d != 8 && d != 32)
            throw Lept.Arg(func, "pixs not 8 or 32 bpp");
        if (reduction < 2 || reduction > 16)
            throw Lept.Arg(func, "reduction must be between 2 and 16");

            /* If pixim exists, verify that it is not all foreground. */
        if (pixim != null) {
            Invert(pixim, pixim);
            allfg = pixim.Zero();
            Invert(pixim, pixim);
            if (allfg)
                throw Lept.Arg(func, "pixim all foreground");
        }

        pixd = null;
        if (d == 8) {
            Pix? pixm = GetBackgroundGrayMapMorph(pixim, reduction, size);
            if (pixm == null)
                throw Lept.Fail(func, "pixm not made");
            Pix? pixmi = TryGetInvBackgroundMap(pixm, bgval, 0, 0);
            if (pixmi == null)
                Log.Error(func, "pixmi not made");
            else
                pixd = ApplyInvBackgroundGrayMap(pixmi, reduction, reduction);
        }
        else {  /* d == 32 */
            bool ok = GetBackgroundRGBMapMorph(pixim, reduction, size,
                                               out Pix? pixmr, out Pix? pixmg, out Pix? pixmb);
            if (!ok || pixmr == null || pixmg == null || pixmb == null)
                throw Lept.Fail(func, "not all pixm*");

            Pix? pixmri = TryGetInvBackgroundMap(pixmr, bgval, 0, 0);
            Pix? pixmgi = TryGetInvBackgroundMap(pixmg, bgval, 0, 0);
            Pix? pixmbi = TryGetInvBackgroundMap(pixmb, bgval, 0, 0);
            if (pixmri == null || pixmgi == null || pixmbi == null)
                Log.Error(func, "not all pixm*i are made");
            else
                pixd = ApplyInvBackgroundRGBMap(pixmri, pixmgi, pixmbi,
                                                reduction, reduction);
        }

        if (pixd == null)
            throw Lept.Fail(func, "pixd not made");
        pixd.CopyResolution(this);
        return pixd;
    }

    /*-------------------------------------------------------------------------*
