            throw Lept.Arg(func, "pixs not 32 bpp");
        if (pixmr.Depth != 16 || pixmg.Depth != 16 || pixmb.Depth != 16)
            throw Lept.Arg(func, "pix maps not all 16 bpp");
        if (sx == 0 || sy == 0)
            throw Lept.Arg(func, "invalid sx and/or sy");

