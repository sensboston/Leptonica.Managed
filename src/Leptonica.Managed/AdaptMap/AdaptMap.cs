    // leptonica: pixBackgroundNormFlex (adaptmap.c)
    /// <summary>Background normalization that adapts flexibly to a quickly varying background.</summary>
    /// <param name="sx">desired tile dimensions; size may vary;
    ///                  use values between 3 and 10</param>
    /// <param name="sy">desired tile dimensions; size may vary;
    ///                  use values between 3 and 10</param>
    /// <param name="smoothx">half-width of convolution kernel applied to
    ///                       threshold array: use values between 1 and 3</param>
    /// <param name="smoothy">half-height of convolution kernel applied to
    ///                       threshold array: use values between 1 and 3</param>
    /// <param name="delta">difference parameter in basin filling; use 0 to skip</param>
    /// <returns>pixd 8 bpp, background-normalized</returns>
    /// <remarks>
    /// (1) This does adaptation flexibly to a quickly varying background.
    ///     For that reason, all input parameters should be small.
    /// (2) sx and sy give the tile size; they should be in [5 - 7].
    /// (3) The full width and height of the convolution kernel
    ///     are (2 * smoothx + 1) and (2 * smoothy + 1).  They
    ///     should be in [1 - 2].
    /// (4) Basin filling is used to fill the large fg regions.  The
    ///     parameter %delta measures the height that the black
    ///     background is raised from the local minima.  By raising
    ///     the background, it is possible to threshold the large
    ///     fg regions to foreground.  If %delta is too large,
    ///     bg regions will be lifted, causing thickening of
    ///     the fg regions.  Use 0 to skip.
    /// </remarks>
    public Pix BackgroundNormFlex(int sx, int sy, int smoothx, int smoothy, int delta)
    {
        const string func = "pixBackgroundNormFlex";
        float scalex, scaley;
        Pix pixt, pixsd, pixbg, pixbgi, pixd;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (sx < 3 || sy < 3)
            throw Lept.Arg(func, "sx and/or sy less than 3");
        if (sx > 10 || sy > 10)
            throw Lept.Arg(func, "sx and/or sy exceed 10");
        if (smoothx < 1 || smoothy < 1)
            throw Lept.Arg(func, "smooth params less than 1");
        if (smoothx > 3 || smoothy > 3)
            throw Lept.Arg(func, "smooth params exceed 3");

            /* Generate the bg estimate using smoothed average with subsampling */
        scalex = (float)(1.0 / (float)sx);
        scaley = (float)(1.0 / (float)sy);
        pixt = ScaleSmooth(scalex, scaley);

            /* Do basin filling on the bg estimate if requested */
        if (delta <= 0)
            pixsd = Clone(pixt);
        else {
            pixt.LocalExtrema(0, 0, out Pix pixmin, out _);
            pixsd = pixmin.SeedfillGrayBasin(pixt, delta, 4);
        }
        pixbg = pixsd.ExtendByReplication(1, 1);

            /* Map the bg to 200 */
        pixbgi = pixbg.GetInvBackgroundMap(200, smoothx, smoothy);
        pixd = ApplyInvBackgroundGrayMap(pixbgi, sx, sy);

        return pixd;
    }

    /*------------------------------------------------------------------*
     *                    Adaptive contrast normalization               *
     *------------------------------------------------------------------*/
    // leptonica: pixContrastNorm (adaptmap.c)
    /// <summary>Adaptively expands the contrast to the full dynamic range in each tile.</summary>
    /// <param name="pixd">[optional] 8 bpp; null or equal to pixs</param>
    /// <param name="pixs">8 bpp grayscale; not colormapped</param>
    /// <param name="sx">tile width</param>
    /// <param name="sy">tile height</param>
    /// <param name="mindiff">minimum difference to accept as valid</param>
    /// <param name="smoothx">half-width of convolution kernel applied to
    ///                       min and max arrays: use 0 for no smoothing</param>
    /// <param name="smoothy">half-height of convolution kernel applied to
    ///                       min and max arrays: use 0 for no smoothing</param>
    /// <returns>pixd always</returns>
    /// <remarks>
    /// (1) This function adaptively attempts to expand the contrast
    ///     to the full dynamic range in each tile.  If the contrast in
    ///     a tile is smaller than %mindiff, it uses the min and max
    ///     pixel values from neighboring tiles.  It also can use
    ///     convolution to smooth the min and max values from
    ///     neighboring tiles.  After all that processing, it is
    ///     possible that the actual pixel values in the tile are outside
    ///     the computed [min ... max] range for local contrast
    ///     normalization.  Such pixels are taken to be at either 0
    ///     (if below the min) or 255 (if above the max).
    /// (2) pixd can be equal to pixs (in-place operation) or
    ///     null (makes a new pixd).
    /// (3) sx and sy give the tile size; they are typically at least 20.
    /// (4) mindiff is used to eliminate results for tiles where it is
    ///     likely that either fg or bg is missing.  A value around 50
    ///     or more is reasonable.
    /// (5) The full width and height of the convolution kernel
    ///     are (2 * smoothx + 1) and (2 * smoothy + 1).  Some smoothing
    ///     is typically useful, and we limit the smoothing half-widths
    ///     to the range from 0 to 8.
    /// (6) A linear TRC (gamma = 1.0) is applied to increase the contrast
    ///     in each tile.  The result can subsequently be globally corrected,
    ///     by applying pixGammaTRC() with arbitrary values of gamma
    ///     and the 0 and 255 points of the mapping.
    /// </remarks>
    public static Pix ContrastNorm(Pix? pixd, Pix pixs, int sx, int sy, int mindiff,
                                   int smoothx, int smoothy)
    {
        const string func = "pixContrastNorm";
        Pix pixmin, pixmax;

        if (pixs.Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (pixd != null && pixd != pixs)
            throw Lept.Arg(func, "pixd not null or == pixs");
        if (pixs.Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (sx < 5 || sy < 5)
            throw Lept.Arg(func, "sx and/or sy less than 5");
        if (smoothx < 0 || smoothy < 0)
            throw Lept.Arg(func, "smooth params less than 0");
        if (smoothx > 8 || smoothy > 8)
            throw Lept.Arg(func, "smooth params exceed 8");

            /* Get the min and max pixel values in each tile, and represent
             * each value as a pixel in pixmin and pixmax, respectively. */
        MinMaxTiles(pixs, sx, sy, mindiff, smoothx, smoothy, out pixmin, out pixmax);

            /* For each tile, do a linear expansion of the dynamic range
             * of pixels so that the min value is mapped to 0 and the
             * max value is mapped to 255.  */
        pixd = LinearTRCTiled(pixd, pixs, sx, sy, pixmin, pixmax);

        return pixd;
    }

    // leptonica: pixMinMaxTiles (adaptmap.c)
    /// <summary>Computes filtered and smoothed values for the min and max pixel values in each tile.</summary>
    /// <param name="pixs">8 bpp grayscale; not colormapped</param>
    /// <param name="sx">tile width</param>
    /// <param name="sy">tile height</param>
    /// <param name="mindiff">minimum difference to accept as valid</param>
    /// <param name="smoothx">half-width of convolution kernel applied to
    ///                       min and max arrays: use 0 for no smoothing</param>
    /// <param name="smoothy">half-height of convolution kernel applied to
    ///                       min and max arrays: use 0 for no smoothing</param>
    /// <param name="pixmin">tiled minima</param>
    /// <param name="pixmax">tiled maxima</param>
    /// <remarks>
    /// (1) This computes filtered and smoothed values for the min and
    ///     max pixel values in each tile of the image.
    /// (2) See pixContrastNorm() for usage.
    /// NOTE(upstream): pixContrastNorm() accepts smoothing half-widths up to 8
    /// but this function rejects values above 5, and pixContrastNorm() does not
    /// check the return value.  In C the call then yields a NULL pixmin and
    /// pixmax and pixContrastNorm() returns pixd (NULL, or pixs when in place)
    /// after an error message; here the invalid argument throws.
    /// </remarks>
    private static void MinMaxTiles(Pix pixs, int sx, int sy, int mindiff, int smoothx,
                                    int smoothy, out Pix pixmin, out Pix pixmax)
    {
        const string func = "pixMinMaxTiles";
        int w, h;
        Pix pixmin1, pixmax1, pixmin2, pixmax2;

        pixmin = null!;
        pixmax = null!;
        if (pixs.Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (pixs.Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (sx < 5 || sy < 5)
            throw Lept.Arg(func, "sx and/or sy less than 3");
        if (smoothx < 0 || smoothy < 0)
            throw Lept.Arg(func, "smooth params less than 0");
        if (smoothx > 5 || smoothy > 5)
            throw Lept.Arg(func, "smooth params exceed 5");

            /* Get the min and max values in each tile */
        pixmin1 = pixs.ScaleGrayMinMax(sx, sy, L.L_CHOOSE_MIN);
        pixmax1 = pixs.ScaleGrayMinMax(sx, sy, L.L_CHOOSE_MAX);

        pixmin2 = pixmin1.ExtendByReplication(1, 1);
        pixmax2 = pixmax1.ExtendByReplication(1, 1);

            /* Make sure no value is 0 */
        pixmin2.AddConstantGray(1);
        pixmax2.AddConstantGray(1);

            /* Generate holes where the contrast is too small */
        SetLowContrast(pixmin2, pixmax2, mindiff);

            /* Fill the holes (0 values) */
        pixmin2.GetDimensions(out w, out h, out _);
        pixmin2.FillMapHoles(w, h, L.L_FILL_BLACK);
        pixmax2.FillMapHoles(w, h, L.L_FILL_BLACK);

            /* Smooth if requested */
        if (smoothx > 0 || smoothy > 0) {
            smoothx = Math.Min(smoothx, (w - 1) / 2);
            smoothy = Math.Min(smoothy, (h - 1) / 2);
            pixmin = pixmin2.Blockconv(smoothx, smoothy);
            pixmax = pixmax2.Blockconv(smoothx, smoothy);
        }
        else {
            pixmin = Clone(pixmin2);
            pixmax = Clone(pixmax2);
        }
        pixmin.CopyResolution(pixs);
        pixmax.CopyResolution(pixs);
    }

    // leptonica: pixSetLowContrast (adaptmap.c)
    /// <summary>Sets to 0 the pixels of two images whose difference is smaller than mindiff.</summary>
    /// <param name="pixs1">8 bpp</param>
    /// <param name="pixs2">8 bpp</param>
    /// <param name="mindiff">minimum difference to accept as valid</param>
    /// <returns>true if OK; false if no pixel diffs are large enough (C: return value 1)</returns>
    /// <remarks>
    /// (1) This compares corresponding pixels in pixs1 and pixs2.
    ///     When they differ by less than %mindiff, set the pixel
    ///     values to 0 in each.  Each pixel typically represents a tile
    ///     in a larger image, and a very small difference between
    ///     the min and max in the tile indicates that the min and max
    ///     values are not to be trusted.
    /// (2) If contrast (pixel difference) detection is expected to fail,
    ///     caller should check return value.
    /// </remarks>
    private static bool SetLowContrast(Pix pixs1, Pix pixs2, int mindiff)
    {
        const string func = "pixSetLowContrast";
        int i, j, w, h, d, wpl, val1, val2;
        bool found;

        if (SizesEqual(pixs1, pixs2) == false)
            throw Lept.Arg(func, "pixs1 and pixs2 not equal size");
        pixs1.GetDimensions(out w, out h, out d);
        if (d != 8)
            throw Lept.Arg(func, "depth not 8 bpp");
        if (mindiff > 254) return true;

        uint[] data1 = pixs1.Data;
        uint[] data2 = pixs2.Data;
        wpl = pixs1.Wpl;
        found = false;  /* init to not finding any diffs >= mindiff */
        for (i = 0; i < h; i++) {
            ReadOnlySpan<uint> line1 = data1.AsSpan(i * wpl, wpl);
            ReadOnlySpan<uint> line2 = data2.AsSpan(i * wpl, wpl);
            for (j = 0; j < w; j++) {
                val1 = GetDataByte(line1, j);
                val2 = GetDataByte(line2, j);
                if (Math.Abs(val1 - val2) >= mindiff) {
                    found = true;
                    break;
                }
            }
            if (found) break;
        }
        if (!found) {
            Log.Warning(func, "no pixel pair diffs as large as mindiff\n");
            pixs1.ClearAll();
            pixs2.ClearAll();
            return false;
        }

        for (i = 0; i < h; i++) {
            Span<uint> line1 = data1.AsSpan(i * wpl, wpl);
            Span<uint> line2 = data2.AsSpan(i * wpl, wpl);
            for (j = 0; j < w; j++) {
                val1 = GetDataByte(line1, j);
                val2 = GetDataByte(line2, j);
                if (Math.Abs(val1 - val2) < mindiff) {
                    SetDataByte(line1, j, 0);
                    SetDataByte(line2, j, 0);
                }
            }
        }

        return true;
    }

    // leptonica: pixLinearTRCTiled (adaptmap.c)
    /// <summary>Applies a linear TRC to each tile, mapping the tile min to 0 and the tile max to 255.</summary>
    /// <param name="pixd">[optional] 8 bpp</param>
    /// <param name="pixs">8 bpp, not colormapped</param>
    /// <param name="sx">tile width</param>
    /// <param name="sy">tile height</param>
    /// <param name="pixmin">pix of min values in tiles</param>
    /// <param name="pixmax">pix of max values in tiles</param>
    /// <returns>pixd always</returns>
    /// <remarks>
    /// (1) pixd can be equal to pixs (in-place operation) or
    ///     null (makes a new pixd).
    /// (2) sx and sy give the tile size; they are typically at least 20.
    /// (3) pixmin and pixmax are generated by pixMinMaxTiles()
    /// (4) For each tile, this does a linear expansion of the dynamic
    ///     range so that the min value in the tile becomes 0 and the
    ///     max value in the tile becomes 255.
    /// (5) The LUTs that do the mapping are generated as needed
    ///     and stored for reuse in an integer array within the ptr array iaa[].
    /// </remarks>
    private static Pix LinearTRCTiled(Pix? pixd, Pix pixs, int sx, int sy, Pix pixmin, Pix pixmax)
    {
        const string func = "pixLinearTRCTiled";
        int i, j, k, m, w, h, wt, ht, wpl, wplt, xoff, yoff;
        int minval, maxval, val, sval;
        int[]? ia;
        int[]?[] iaa;

        if (pixs.Depth != 8)
            throw Lept.Arg(func, "pixs undefined or not 8 bpp");
        if (pixd != null && pixd != pixs)
            throw Lept.Arg(func, "pixd not null or == pixs");
        if (pixs.Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (sx < 5 || sy < 5)
            throw Lept.Arg(func, "sx and/or sy less than 5");

        iaa = new int[]?[256];
        pixd = Copy(pixd, pixs);
        pixd.GetDimensions(out w, out h, out _);

        uint[] data = pixd.Data;
        wpl = pixd.Wpl;
        uint[] datamin = pixmin.Data;
        uint[] datamax = pixmax.Data;
        wplt = pixmin.Wpl;
        pixmin.GetDimensions(out wt, out ht, out _);
        for (i = 0; i < ht; i++) {
            ReadOnlySpan<uint> linemin = datamin.AsSpan(i * wplt, wplt);
            ReadOnlySpan<uint> linemax = datamax.AsSpan(i * wplt, wplt);
            yoff = sy * i;
            for (j = 0; j < wt; j++) {
                xoff = sx * j;
                minval = GetDataByte(linemin, j);
                maxval = GetDataByte(linemax, j);
                if (maxval == minval) {
                    Log.Error(func, $"shouldn't happen! i,j = {i},{j}, minval = {minval}\n");
                    continue;
                }
                if ((ia = IaaGetLinearTRC(iaa, maxval - minval)) == null) {
                    Log.Error(func, $"failure to make ia for j = {j}!\n");
                    continue;
                }
                for (k = 0; k < sy && yoff + k < h; k++) {
                    Span<uint> tline = data.AsSpan((sy * i + k) * wpl, wpl);
                    for (m = 0; m < sx && xoff + m < w; m++) {
                        val = GetDataByte(tline, xoff + m);
                        sval = val - minval;
                        sval = Math.Max(0, sval);
                        SetDataByte(tline, xoff + m, ia[sval]);
                    }
                }
            }
        }

        return pixd;
    }

    // leptonica: iaaGetLinearTRC (adaptmap.c)
    /// <summary>Returns the LUT for a given difference between max and min, making it if needed.</summary>
    /// <param name="iaa">bare array of 256 arrays of int</param>
    /// <param name="diff">between min and max pixel values that are
    ///                    to be mapped to 0 and 255</param>
    /// <returns>ia LUT with input (val - minval) and output a
    ///               value between 0 and 255</returns>
    private static int[]? IaaGetLinearTRC(int[]?[] iaa, int diff)
    {
        int i;
        int[] ia;
        float factor;

        if (iaa[diff] != null)  /* already have it */
           return iaa[diff];

        ia = new int[256];
        iaa[diff] = ia;
        if (diff == 0) {  /* shouldn't happen */
            for (i = 0; i < 256; i++)
                ia[i] = 128;
        }
        else {
            factor = (float)(255.0 / (float)diff);
            for (i = 0; i < diff + 1; i++)
                ia[i] = (int)(factor * i + 0.5);
            for (i = diff + 1; i < 256; i++)
                ia[i] = 255;
        }

        return ia;
    }

    /*------------------------------------------------------------------*
     *   Adaptive normalization with MinMax conversion of RGB to gray,  *
     *   contrast enhancement and optional 2x upscale binarization      *
     *------------------------------------------------------------------*/
    // leptonica: pixBackgroundNormTo1MinMax (adaptmap.c)
    /// <summary>Convenience binarization: MinMax gray conversion, background normalization, contrast enhancement and thresholding.</summary>
    /// <param name="contrast">1 to 10: 1 reduces contrast; 10 is maximum enhancement</param>
    /// <param name="scalefactor">1 (no change); 2 (2x upscale)</param>
    /// <returns>1 bpp pix</returns>
    /// <remarks>
    /// (1) This is a convenience binarization function that does four things:
    ///     * Generates a grayscale image with color enhancement to gray
    ///     * Background normalization
    ///     * Optional contrast enhancement
    ///     * Binarizes either at input resolution or with 2x upscaling
    /// (2) If the %pixs is 1 bpp, returns a copy.
    /// (3) The contrast increasing parameter %contrast takes values {1, ... 10}.
    ///     For decent scans, contrast = 1 is recommended.  Use a larger
    ///     value if important details are lost in binarization.
    /// (4) Valid values of %scalefactor are 1 and 2.
    /// </remarks>
    public Pix BackgroundNormTo1MinMax(int contrast, int scalefactor)
    {
        const string func = "pixBackgroundNormTo1MinMax";
        Pix pix1, pix2, pixd;

        if (contrast < 1 || contrast > 10)
            throw Lept.Arg(func, "contrast not in [1 ... 10]");
        if (scalefactor != 1 && scalefactor != 2)
            throw Lept.Arg(func, "scalefactor not 1 or 2");

        if (Depth == 1) {
            pixd = Copy(null, this);
        } else {
            pix1 = ConvertTo8MinMax();
            pix2 = pix1.BackgroundNormSimple(null, null);
            pix2.SelectiveContrastMod(contrast);
            if (scalefactor == 1)
                pixd = pix2.ThresholdToBinary(180);
            else  /* scalefactor == 2 */
                pixd = pix2.ScaleGray2xLIThresh(180);
        }
        return pixd;
    }

    // leptonica: pixConvertTo8MinMax (adaptmap.c)
    /// <summary>Converts any depth, with or without colormap, to 8 bpp, rendering color strongly into black.</summary>
    /// <returns>8 bpp pix</returns>
    /// <remarks>
    /// (1) This is a special version of pixConvert1To8() that removes any
    ///     existing colormap and uses pixConvertRGBToGrayMinMax()
    ///     to strongly render color into black.
    /// </remarks>
    public Pix ConvertTo8MinMax()
    {
        const string func = "pixConvertTo8MinMax";
        int d = Depth;
        if (d == 1) {
            return Convert1To8(null, this, 255, 0);
        } else if (d == 2) {
            return Convert2To8(0, 85, 170, 255, false);
        } else if (d == 4) {
            return Convert4To8(false);
        } else if (d == 8) {
            if (Colormap != null)
                return RemoveColormap(L.REMOVE_CMAP_TO_GRAYSCALE);
            else
                return Copy(null, this);
        } else if (d == 16) {
            return Convert16To8(L.L_MS_BYTE);
        } else if (d == 32) {
            return ConvertRGBToGrayMinMax(L.L_CHOOSE_MIN);
        }

        throw Lept.Fail(func, $"Invalid depth d = {d}");
    }

    // leptonica: pixSelectiveContrastMod (adaptmap.c)
    /// <summary>In-place contrast enhancement of an 8 bpp image that has been background normalized to 200.</summary>
    /// <param name="contrast">1 (default value) for some contrast reduction;
    ///                        10 for maximum contrast enhancement.</param>
    /// <remarks>
    /// (1) This does in-place contrast enhancement on 8 bpp grayscale that
    ///     has been background normalized to 200.  Therefore, there should
    ///     be no gray pixels above 200 in %pixs.  For general contrast
    ///     enhancement on gray or color images, see pixContrastTRC().
    /// (2) Caller restricts %contrast to [1 ... 10].
    /// (3) Use %contrast = 1 for minimum contrast enhancement (which will
    ///     remove some speckle noise) and %contrast = 10 for maximum
    ///     darkening.
    /// (4) We use 200 for the white point in all transforms.  Using a
    ///     white point above 200 will darken all grayscale pixels.
    /// </remarks>
    private void SelectiveContrastMod(int contrast)
    {
        if (Depth != 8)
            throw Lept.Arg("pixSelectiveContrastMod", "pixs not defined or not 8 bpp");

        if (contrast == 1)
            GammaTRC(this, this, 2.0f, 50, 200);
        else if (contrast == 2)
            GammaTRC(this, this, 1.8f, 60, 200);
        else if (contrast == 3)
            GammaTRC(this, this, 1.6f, 70, 200);
        else if (contrast == 4)
            GammaTRC(this, this, 1.4f, 80, 200);
        else if (contrast == 5)
            GammaTRC(this, this, 1.2f, 90, 200);
        else if (contrast == 6)
            GammaTRC(this, this, 1.0f, 100, 200);
        else if (contrast == 7)
            GammaTRC(this, this, 0.85f, 110, 200);
        else if (contrast == 8)
            GammaTRC(this, this, 0.7f, 120, 200);
        else if (contrast == 9)
            GammaTRC(this, this, 0.6f, 130, 200);
        else  /* contrast == 10 */
            GammaTRC(this, this, 0.5f, 140, 200);
    }
