    /* Default input parameters for pixBackgroundNormSimple()
     * Notes:
     *    (1) mincount must never exceed the tile area (width * height)
     *    (2) bgval must be sufficiently below 255 to avoid accidental
     *        saturation; otherwise it should be large to avoid
     *        shrinking the dynamic range
     *    (3) results should otherwise not be sensitive to these values
     */
    private const int DefaultTileWidth = 10;     /* default tile width    */
    private const int DefaultTileHeight = 15;    /* default tile height   */
    private const int DefaultFgThreshold = 60;   /* default fg threshold  */
    private const int DefaultMinCount = 40;      /* default minimum count */
    private const int DefaultBgVal = 200;        /* default bg value      */
    private const int DefaultXSmoothSize = 2;    /* default x smooth size */
    private const int DefaultYSmoothSize = 1;    /* default y smooth size */

    /*------------------------------------------------------------------*
     *      Clean background to white using background normalization    *
     *------------------------------------------------------------------*/
    // leptonica: pixCleanBackgroundToWhite (adaptmap.c)
    /// <summary>Cleans the background to white using background normalization.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null</param>
    /// <param name="pixg">[optional] 8 bpp grayscale version; can be null</param>
    /// <param name="gamma">gamma correction; must be &gt; 0.0; typically ~1.0</param>
    /// <param name="blackval">dark value to set to black (0)</param>
    /// <param name="whiteval">light value to set to white (255)</param>
    /// <returns>pixd 8 bpp or 32 bpp rgb</returns>
    /// <remarks>
    /// (1) This is a simplified interface for cleaning an image.
    ///     For comparison, see pixAdaptThresholdToBinaryGen().
    /// (2) The suggested default values for the input parameters are:
    ///       gamma:    1.0  (reduce this to increase the contrast; e.g.,
    ///                       for light text)
    ///       blackval   70  (a bit more than 60)
    ///       whiteval  190  (a bit less than 200)
    /// (3) Note: the whiteval must not exceed 200, which is the value
    ///     that the background is set to in pixBackgroundNormSimple().
    /// </remarks>
    public Pix CleanBackgroundToWhite(Pix? pixim, Pix? pixg, float gamma, int blackval,
                                      int whiteval)
    {
        const string func = "pixCleanBackgroundToWhite";
        int d = Depth;
        if (d != 8 && d != 32)
            throw Lept.Arg(func, "depth not 8 or 32");
        if (whiteval > 200) {
            Log.Warning(func, $"white value {whiteval} must not exceed 200; reset to 190");
            whiteval = 190;
        }

        Pix pixd = BackgroundNormSimple(pixim, pixg);
        GammaTRC(pixd, pixd, gamma, blackval, whiteval);
        return pixd;
    }

