     *                  Non-adaptive (global) mapping                   *
     *------------------------------------------------------------------*/
    // leptonica: pixGlobalNormRGB (adaptmap.c)
    /// <summary>Global linear normalization of the r, g and b components of a 32 bpp or colormapped image.</summary>
    /// <param name="pixd">[optional] null, existing or equal to pixs</param>
    /// <param name="pixs">32 bpp rgb, or colormapped</param>
    /// <param name="rval">pixel value in pixs that is linearly mapped to mapval</param>
    /// <param name="gval">pixel value in pixs that is linearly mapped to mapval</param>
    /// <param name="bval">pixel value in pixs that is linearly mapped to mapval</param>
    /// <param name="mapval">use 255 for mapping to white</param>
    /// <returns>pixd 32 bpp rgb or colormapped</returns>
    /// <remarks>
    /// (1) The value of pixd determines if the results are written to a
    ///     new pix (use NULL), in-place to pixs (use pixs), or to some
    ///     other existing pix.
    /// (2) This does a global normalization of an image where the
    ///     r,g,b color components are not balanced.  Thus, white in pixs is
    ///     represented by a set of r,g,b values that are not all 255.
    /// (3) The input values (rval, gval, bval) should be chosen to
    ///     represent the gray color (mapval, mapval, mapval) in src.
    ///     Thus, this function will map (rval, gval, bval) to that gray color.
    /// (4) Typically, mapval = 255, so that (rval, gval, bval)
    ///     corresponds to the white point of src.  In that case, these
    ///     parameters should be chosen so that few pixels have higher values.
    /// (5) In all cases, we do a linear TRC separately on each of the
    ///     components, saturating at 255.
    /// (6) If the input pix is 8 bpp without a colormap, you can get
    ///     this functionality with mapval = 255 by calling:
    ///         pixGammaTRC(pixd, pixs, 1.0, 0, bgval);
    ///     where bgval is the value you want to be mapped to 255.
    ///     Or more generally, if you want bgval to be mapped to mapval:
    ///         pixGammaTRC(pixd, pixs, 1.0, 0, 255 * bgval / mapval);
    /// </remarks>
    public static Pix GlobalNormRGB(Pix? pixd, Pix pixs, int rval, int gval, int bval, int mapval)
    {
        const string func = "pixGlobalNormRGB";
        int w, h, d, i, j, ncolors, rv, gv, bv, wpl;
        int[] rarray, garray, barray;
        Numa nar, nag, nab;
        PixColormap? cmap;

        cmap = pixs.Colormap;
        pixs.GetDimensions(out w, out h, out d);
        if (cmap == null && d != 32)
            throw Lept.Arg(func, "pixs not cmapped or 32 bpp");
        if (mapval <= 0) {
            Log.Warning(func, "mapval must be > 0; setting to 255\n");
            mapval = 255;
        }

            /* Prepare pixd to be a copy of pixs */
        pixd = Copy(pixd, pixs);

            /* Generate the TRC maps for each component.  Make sure the
             * upper range for each color is greater than zero. */
        nar = Numa.GammaTRC(1.0f, 0, Math.Max(1, 255 * rval / mapval));
        nag = Numa.GammaTRC(1.0f, 0, Math.Max(1, 255 * gval / mapval));
        nab = Numa.GammaTRC(1.0f, 0, Math.Max(1, 255 * bval / mapval));

            /* Extract copies of the internal arrays */
        rarray = nar.GetIArray();
        garray = nag.GetIArray();
        barray = nab.GetIArray();

        if (cmap != null) {
            ncolors = cmap.Count;
            for (i = 0; i < ncolors; i++) {
                cmap.GetColor(i, out rv, out gv, out bv);
                cmap.ResetColor(i, rarray[rv], garray[gv], barray[bv]);
            }
        }
        else {
            uint[] data = pixd.Data;
            wpl = pixd.Wpl;
            for (i = 0; i < h; i++) {
                int line = i * wpl;
                for (j = 0; j < w; j++) {
                    ExtractRGBValues(data[line + j], out rv, out gv, out bv);
                    ComposeRGBPixel(rarray[rv], garray[gv], barray[bv], out data[line + j]);
                }
            }
        }

        return pixd;
    }

    // leptonica: pixGlobalNormNoSatRGB (adaptmap.c)
    /// <summary>Global normalization of a 32 bpp image, with the output scaled back so that a controlled fraction of components saturates.</summary>
    /// <param name="pixd">[optional] null, existing or equal to pixs</param>
    /// <param name="pixs">32 bpp rgb</param>
    /// <param name="rval">pixel value in pixs that is linearly mapped to mapval; but see below</param>
    /// <param name="gval">pixel value in pixs that is linearly mapped to mapval; but see below</param>
    /// <param name="bval">pixel value in pixs that is linearly mapped to mapval; but see below</param>
    /// <param name="factor">subsampling factor; integer &gt;= 1</param>
    /// <param name="rank">between 0.0 and 1.0; typ. use a value near 1.0</param>
    /// <returns>pixd 32 bpp rgb</returns>
    /// <remarks>
    /// (1) This is a version of pixGlobalNormRGB(), where the output
    ///     intensity is scaled back so that a controlled fraction of
    ///     pixel components is allowed to saturate.  See comments in
    ///     pixGlobalNormRGB().
    /// (2) The value of pixd determines if the results are written to a
    ///     new pix (use NULL), in-place to pixs (use pixs), or to some
    ///     other existing pix.
    /// (3) This does a global normalization of an image where the
    ///     r,g,b color components are not balanced.  Thus, white in pixs is
    ///     represented by a set of r,g,b values that are not all 255.
    /// (4) The input values (rval, gval, bval) can be chosen to be the
    ///     color that, after normalization, becomes white background.
    ///     For images that are mostly background, the closer these values
    ///     are to the median component values, the closer the resulting
    ///     background will be to gray, becoming white at the brightest places.
    /// (5) The mapval used in pixGlobalNormRGB() is computed here to
    ///     avoid saturation of any component in the image (save for a
    ///     fraction of the pixels given by the input rank value).
    /// </remarks>
    public static Pix GlobalNormNoSatRGB(Pix? pixd, Pix pixs, int rval, int gval, int bval,
                                         int factor, float rank)
    {
        const string func = "pixGlobalNormNoSatRGB";
        int mapval;
        float rankrval, rankgval, rankbval;
        float rfract, gfract, bfract, maxfract;

        if (pixs.Depth != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
        if (factor < 1)
            throw Lept.Arg(func, "sampling factor < 1");
        if (rank < 0.0 || rank > 1.0)
            throw Lept.Arg(func, "rank not in [0.0 ... 1.0]");
        if (rval <= 0 || gval <= 0 || bval <= 0)
            throw Lept.Arg(func, "invalid estim. color values");

            /* The max value for each component may be larger than the
             * input estimated background value.  In that case, mapping
             * for those pixels would saturate.  To prevent saturation,
             * we compute the fraction for each component by which we
             * would oversaturate.  Then take the max of these, and
             * reduce, uniformly over all components, the output intensity
             * by this value.  Then no component will saturate.
             * In practice, if rank < 1.0, a fraction of pixels
             * may have a component saturate.  By keeping rank close to 1.0,
             * that fraction can be made arbitrarily small. */
        pixs.GetRankValueMaskedRGB(null, 0, 0, factor, rank, out rankrval,
                                   out rankgval, out rankbval);
        rfract = rankrval / (float)rval;
        gfract = rankgval / (float)gval;
        bfract = rankbval / (float)bval;
        maxfract = Math.Max(rfract, gfract);
        maxfract = Math.Max(maxfract, bfract);

        mapval = (int)(255.0 / maxfract);
        pixd = GlobalNormRGB(pixd, pixs, rval, gval, bval, mapval);
        return pixd;
    }

