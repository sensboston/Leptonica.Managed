    // leptonica: pixGetBackgroundGrayMap (adaptmap.c)
    /// <summary>Measures the background of an 8 bpp image in tiles.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null;
    ///                     it should not have only foreground pixels</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <param name="thresh">threshold for determining foreground</param>
    /// <param name="mincount">min threshold on counts in a tile</param>
    /// <returns>8 bpp grayscale map; null if the map holes could not be filled</returns>
    /// <remarks>
    /// (1) The background is measured in regions that don't have
    ///     images.  It is then propagated into the image regions,
    ///     and finally smoothed in each image region.
    /// </remarks>
    public Pix? GetBackgroundGrayMap(Pix? pixim, int sx, int sy, int thresh, int mincount)
    {
        const string func = "pixGetBackgroundGrayMap";
        int w, h, wd, hd, wim, him, wpls, wplim, wpld, wplf;
        int xim, yim, delx, nx, ny, i, j, k, m;
        int count, sum, val8;
        bool empty;
        bool fgpixels;
        float scalex, scaley;
        Pix pixd, piximi, pixb, pixf, pixims;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (pixim != null && pixim.Depth != 1)
            throw Lept.Arg(func, "pixim not 1 bpp");
        if (sx < 4 || sy < 4)
            throw Lept.Arg(func, "sx and sy must be >= 4");
        if (mincount > sx * sy) {
            Log.Warning(func, "mincount too large for tile size\n");
            mincount = (sx * sy) / 3;
        }

            /* Evaluate the 'image' mask, pixim, and make sure
             * it is not all fg. */
        fgpixels = false;  /* boolean for existence of fg pixels in the image mask. */
        if (pixim != null) {
            piximi = Invert(null, pixim);  /* set non-'image' pixels to 1 */
            empty = piximi.Zero();
            if (empty)
                throw Lept.Arg(func, "pixim all fg; no background");
            empty = pixim.Zero();
            if (!empty)  /* there are fg pixels in pixim */
                fgpixels = true;
        }

            /* Generate the foreground mask, pixf, which is at full resolution.
             * mask has a value 0 for pixels in pixs that are likely to be
             * in the background, which is the condition for including
             * those source pixels when taking an average of the background
             * values for each tile.  */
        pixb = ThresholdToBinary(thresh);
        pixf = pixb.MorphSequence("d7.1 + d1.7", 0);


        /* ------------- Set up the output map pixd --------------- */
            /* In pixd, each 8 bit pixel represents a tile of size (sx, sy)
             * in pixs.  Each pixel in pixd will be filled with the average
             * background value of that tile in pixs.  */
        w = Width;
        h = Height;
        wd = (w + sx - 1) / sx;
        hd = (h + sy - 1) / sy;
        pixd = Create(wd, hd, 8);

            /* Here we only compute map values in pixd for tiles that
             * are complete.  In general, the extreme right and bottom
             * tiles in pixs, which correspond to the rightmost column
             * and bottom row of pixd, are not complete.  These will
             * be filled in later.
             *
             * Use the full resolution mask pixf to decide which pixels
             * are used in each tile to estimate the background value.
             * After this operation, pixels in the background map pixd
             * that have not been set must be filled using adjacent pixels. */
        nx = w / sx;
        ny = h / sy;
        wpls = Wpl;
        uint[] datas = Data;
        wpld = pixd.Wpl;
        uint[] datad = pixd.Data;
        wplf = pixf.Wpl;
        uint[] dataf = pixf.Data;
        for (i = 0; i < ny; i++) {
            Span<uint> lined = datad.AsSpan(i * wpld, wpld);
            for (j = 0; j < nx; j++) {
                delx = j * sx;
                sum = 0;
                count = 0;
                for (k = 0; k < sy; k++) {
                    ReadOnlySpan<uint> lines = datas.AsSpan((sy * i + k) * wpls, wpls);
                    ReadOnlySpan<uint> linef = dataf.AsSpan((sy * i + k) * wplf, wplf);
                    for (m = 0; m < sx; m++) {
                        if (GetDataBit(linef, delx + m) == 0) {
                            sum += GetDataByte(lines, delx + m);
                            count++;
                        }
                    }
                }
                if (count >= mincount) {
                    val8 = sum / count;
                    SetDataByte(lined, j, val8);
                }
            }
        }

            /* If there is an optional mask with fg pixels, erase the previous
             * calculation for the corresponding map pixels, setting the
             * map values to 0.   Then, when all the map holes are filled,
             * these erased pixels will be set by the surrounding map values,
             * along with the ones not set above using the background values.
             *
             * The calculation here is relatively efficient: for each pixel
             * in pixd (which corresponds to a tile of mask pixels in pixim)
             * we look only at the pixel in pixim that is at the center
             * of the tile.  If the mask pixel is ON, we reset the map
             * pixel in pixd to 0, so that it can later be filled in. */
        if (pixim != null && fgpixels) {
            wim = pixim.Width;
            him = pixim.Height;
            uint[] dataim = pixim.Data;
            wplim = pixim.Wpl;
            for (i = 0; i < ny; i++) {
                yim = i * sy + sy / 2;
                if (yim >= him)
                    break;
                ReadOnlySpan<uint> lineim = dataim.AsSpan(yim * wplim, wplim);
                for (j = 0; j < nx; j++) {
                    xim = j * sx + sx / 2;
                    if (xim >= wim)
                        break;
                    if (GetDataBit(lineim, xim) != 0)
                        pixd.SetPixel(j, i, 0);
                }
            }
        }

            /* Fill all the holes in the map.
             * Note that (nx,ny) represent the numbers of complete tiles
             * in the x and y directions of pixs, whereas the dimensions
             * of pixd are usually larger by 1. */
        if (!pixd.FillMapHoles(nx, ny, L.L_FILL_BLACK)) {
            Log.Warning(func, "can't fill holes and make the map\n");
            return null;
        }

            /* Finally, for each connected region corresponding to the
             * 'image' mask, reset all pixels to their average value.
             * Each of these components represents an image (or part of one)
             * in the input, and this smooths the background values
             * in each of these regions. */
        if (pixim != null && fgpixels) {
            scalex = (float)(1.0 / (float)sx);
            scaley = (float)(1.0 / (float)sy);
            pixims = pixim.ScaleBySampling(scalex, scaley);
            pixd.SmoothConnectedRegions(pixims, 2);
        }

        pixd.CopyResolution(this);
        return pixd;
    }

    // leptonica: pixGetBackgroundRGBMap (adaptmap.c)
    /// <summary>Measures the background of a 32 bpp image in tiles, for each component.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null; it
    ///                     should not have all foreground pixels</param>
    /// <param name="pixg">[optional] 8 bpp grayscale version; can be null</param>
    /// <param name="sx">tile width in pixels</param>
    /// <param name="sy">tile height in pixels</param>
    /// <param name="thresh">threshold for determining foreground</param>
    /// <param name="mincount">min threshold on counts in a tile</param>
    /// <param name="pixmr">red component map</param>
    /// <param name="pixmg">green component map</param>
    /// <param name="pixmb">blue component map</param>
    /// <returns>true if the maps were made; false (with null maps) if the map holes could not be filled</returns>
    /// <remarks>
    /// (1) If pixg, which is a grayscale version of pixs, is provided,
    ///     use this internally to generate the foreground mask.
    ///     Otherwise, a grayscale version of pixs will be generated
    ///     from the green component only, used, and destroyed.
    /// </remarks>
    public bool GetBackgroundRGBMap(Pix? pixim, Pix? pixg, int sx, int sy, int thresh,
                                    int mincount, out Pix? pixmr, out Pix? pixmg,
                                    out Pix? pixmb)
    {
        const string func = "pixGetBackgroundRGBMap";
        int w, h, wm, hm, wim, him, wpls, wplim, wplf;
        int xim, yim, delx, nx, ny, i, j, k, m;
        int count, rsum, gsum, bsum, rval, gval, bval;
        bool empty;
        bool fgpixels;
        uint pixel;
        float scalex, scaley;
        Pix piximi, pixgc, pixb, pixf, pixims;

        pixmr = pixmg = pixmb = null;
        if (Depth != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
        if (pixim != null && pixim.Depth != 1)
            throw Lept.Arg(func, "pixim not 1 bpp");
        if (sx < 4 || sy < 4)
            throw Lept.Arg(func, "sx and sy must be >= 4");
        if (mincount > sx * sy) {
            Log.Warning(func, "mincount too large for tile size\n");
            mincount = (sx * sy) / 3;
        }

            /* Evaluate the mask pixim and make sure it is not all foreground */
        fgpixels = false;  /* boolean for existence of fg mask pixels */
        if (pixim != null) {
            piximi = Invert(null, pixim);  /* set non-'image' pixels to 1 */
            empty = piximi.Zero();
            if (empty)
                throw Lept.Arg(func, "pixim all fg; no background");
            empty = pixim.Zero();
            if (!empty)  /* there are fg pixels in pixim */
                fgpixels = true;
        }

            /* Generate the foreground mask.  These pixels will be
             * ignored when computing the background values. */
        if (pixg != null)  /* use the input grayscale version if it is provided */
            pixgc = Clone(pixg);
        else
            pixgc = ConvertRGBToGrayFast();
        pixb = pixgc.ThresholdToBinary(thresh);
        pixf = pixb.MorphSequence("d7.1 + d1.7", 0);

            /* Generate the output mask images */
        w = Width;
        h = Height;
        wm = (w + sx - 1) / sx;
        hm = (h + sy - 1) / sy;
        Pix pixr = Create(wm, hm, 8);
        Pix pixgr = Create(wm, hm, 8);
        Pix pixbl = Create(wm, hm, 8);

        /* ------------- Set up the mapping images --------------- */
            /* Note: we only compute map values in tiles that are complete.
             * In general, tiles at right and bottom edges will not be
             * complete, and we must fill them in later. */
        nx = w / sx;
        ny = h / sy;
        wpls = Wpl;
        uint[] datas = Data;
        wplf = pixf.Wpl;
        uint[] dataf = pixf.Data;
        for (i = 0; i < ny; i++) {
            for (j = 0; j < nx; j++) {
                delx = j * sx;
                rsum = gsum = bsum = 0;
                count = 0;
                for (k = 0; k < sy; k++) {
                    int lines = (sy * i + k) * wpls;
                    ReadOnlySpan<uint> linef = dataf.AsSpan((sy * i + k) * wplf, wplf);
                    for (m = 0; m < sx; m++) {
                        if (GetDataBit(linef, delx + m) == 0) {
                            pixel = datas[lines + delx + m];
                            rsum += (int)(pixel >> 24);
                            gsum += (int)((pixel >> 16) & 0xff);
                            bsum += (int)((pixel >> 8) & 0xff);
                            count++;
                        }
                    }
                }
                if (count >= mincount) {
                    rval = rsum / count;
                    gval = gsum / count;
                    bval = bsum / count;
                    pixr.SetPixel(j, i, (uint)rval);
                    pixgr.SetPixel(j, i, (uint)gval);
                    pixbl.SetPixel(j, i, (uint)bval);
                }
            }
        }

            /* If there is an optional mask with fg pixels, erase the previous
             * calculation for the corresponding map pixels, setting the
             * map values in each of the 3 color maps to 0.   Then, when
             * all the map holes are filled, these erased pixels will
             * be set by the surrounding map values. */
        if (pixim != null) {
            wim = pixim.Width;
            him = pixim.Height;
            uint[] dataim = pixim.Data;
            wplim = pixim.Wpl;
            for (i = 0; i < ny; i++) {
                yim = i * sy + sy / 2;
                if (yim >= him)
                    break;
                ReadOnlySpan<uint> lineim = dataim.AsSpan(yim * wplim, wplim);
                for (j = 0; j < nx; j++) {
                    xim = j * sx + sx / 2;
                    if (xim >= wim)
                        break;
                    if (GetDataBit(lineim, xim) != 0) {
                        pixr.SetPixel(j, i, 0);
                        pixgr.SetPixel(j, i, 0);
                        pixbl.SetPixel(j, i, 0);
                    }
                }
            }
        }

        /* ----------------- Now fill in the holes ----------------------- */
        if (!pixr.FillMapHoles(nx, ny, L.L_FILL_BLACK) ||
            !pixgr.FillMapHoles(nx, ny, L.L_FILL_BLACK) ||
            !pixbl.FillMapHoles(nx, ny, L.L_FILL_BLACK)) {
            Log.Warning(func, "can't make the maps\n");
            return false;
        }

            /* Finally, for each connected region corresponding to the
             * fg mask, reset all pixels to their average value. */
        if (pixim != null && fgpixels) {
            scalex = (float)(1.0 / (float)sx);
            scaley = (float)(1.0 / (float)sy);
            pixims = pixim.ScaleBySampling(scalex, scaley);
            pixr.SmoothConnectedRegions(pixims, 2);
            pixgr.SmoothConnectedRegions(pixims, 2);
            pixbl.SmoothConnectedRegions(pixims, 2);
        }

        pixmr = pixr;
        pixmg = pixgr;
        pixmb = pixbl;
        pixmr.CopyResolution(this);
        pixmg.CopyResolution(this);
        pixmb.CopyResolution(this);
        return true;
    }

    // leptonica: pixGetBackgroundGrayMapMorph (adaptmap.c)
    /// <summary>Measures the background of an 8 bpp image by a grayscale closing at reduced scale.</summary>
    /// <param name="pixim">[optional] 1 bpp 'image' mask; can be null; it
    ///                     should not have all foreground pixels</param>
    /// <param name="reduction">factor at which closing is performed</param>
    /// <param name="size">of square Sel for the closing; use an odd number</param>
    /// <returns>grayscale map; null if the map holes could not be filled</returns>
    public Pix? GetBackgroundGrayMapMorph(Pix? pixim, int reduction, int size)
    {
        const string func = "pixGetBackgroundGrayMapMorph";
        int nx, ny;
        bool empty;
        bool fgpixels;
        float scale;
        Pix pixm, pix1, pix2, pix3;
        Pix? pixims;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (pixim != null && pixim.Depth != 1)
            throw Lept.Arg(func, "pixim not 1 bpp");

            /* Evaluate the mask pixim and make sure it is not all foreground. */
        fgpixels = false;  /* boolean for existence of fg mask pixels */
        if (pixim != null) {
            Invert(pixim, pixim);  /* set background pixels to 1 */
            empty = pixim.Zero();
            if (empty)
                throw Lept.Arg(func, "pixim all fg; no background");
            Invert(pixim, pixim);  /* revert to original mask */
            empty = pixim.Zero();
            if (!empty)  /* there are fg pixels in pixim */
                fgpixels = true;
        }

            /* Downscale as requested and do the closing to get the background. */
        scale = (float)(1.0 / (float)reduction);
        pix1 = ScaleBySampling(scale, scale);
        pix2 = pix1.CloseGray(size, size);
        pix3 = pix2.ExtendByReplication(1, 1);

            /* Downscale the image mask, if any, and remove it from the
             * background.  These pixels will be filled in (twice). */
        pixims = null;
        if (pixim != null) {
            pixims = pixim.Scale(scale, scale);
            pixm = pixims.ConvertTo8(false);
            And(pixm, pixm, pix3);
        }
        else
            pixm = Clone(pix3);

            /* Fill all the holes in the map. */
        nx = Width / reduction;
        ny = Height / reduction;
        if (!pixm.FillMapHoles(nx, ny, L.L_FILL_BLACK)) {
            Log.Warning(func, "can't make the map\n");
            return null;
        }

            /* Finally, for each connected region corresponding to the
             * fg mask, reset all pixels to their average value. */
        if (pixim != null && fgpixels)
            pixm.SmoothConnectedRegions(pixims, 2);

        pixm.CopyResolution(this);
        return pixm;
    }

