    /*
     * In C, selaGetBrickName() returns null (with an error message) when the
     * sel is not in the sela; here it throws.  The callers below only need
     * to know whether the sel was found.
     */
    private static readonly FrozenDictionary<(int H, int V), string> s_basicBrickNames = BuildBasicBrickNames();

    private static FrozenDictionary<(int H, int V), string> BuildBasicBrickNames()
    {
        Sela sela = Sela.AddBasic(null);
        var dict = new Dictionary<(int H, int V), string>();
        int n = sela.Count;
        for (int i = 0; i < n; i++) {
            Sel sel = sela.GetSel(i);
            bool allHits = true;
            for (int r = 0; r < sel.Sy && allHits; r++)
                for (int c = 0; c < sel.Sx; c++)
                    if (sel.Data[r][c] != L.SEL_HIT) { allHits = false; break; }
            if (allHits && sel.Name != null)
                dict[(sel.Sx, sel.Sy)] = sel.Name;
        }
        return dict.ToFrozenDictionary();
    }

    private static string? BrickNameOrNull(int hsize, int vsize)
        => s_basicBrickNames.TryGetValue((hsize, vsize), out string? name) ? name : null;

    // leptonica: pixDilateBrickDwa (morphdwa.c)
    /// <summary>Dilates with a brick Sel, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) These implement 2D brick Sels, using linear Sels generated
    ///     with selaAddBasic().
    /// (2) A brick Sel has hits for all elements.
    /// (3) The origin of the Sel is at (x, y) = (hsize/2, vsize/2)
    /// (4) Do separably if both hsize and vsize are &gt; 1.
    /// (5) It is necessary that both horizontal and vertical Sels
    ///     of the input size are defined in the basic sela.
    /// (6) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (7) For clarity, if the case is known, use these patterns:
    ///     (a) pixd = Pix.DilateBrickDwa(null, pixs, ...);
    ///     (b) Pix.DilateBrickDwa(pixs, pixs, ...);
    ///     (c) Pix.DilateBrickDwa(pixd, pixs, ...);
    /// (8) The size of pixd is determined by pixs.
    /// (9) If either linear Sel is not found, this calls
    ///     the appropriate decomposible function.
    /// </remarks>
    public static Pix DilateBrickDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixDilateBrickDwa";
        bool found;
        string? selnameh, selnamev;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");

        if (hsize == 1 && vsize == 1)
            return Copy(pixd, pixs);

        found = true;
        selnameh = selnamev = null;
        if (hsize > 1) {
            selnameh = BrickNameOrNull(hsize, 1);
            if (selnameh == null) found = false;
        }
        if (vsize > 1) {
            selnamev = BrickNameOrNull(1, vsize);
            if (selnamev == null) found = false;
        }
        if (!found) {
            Log.Info(func, "Calling the decomposable dwa function\n");
            return DilateCompBrickDwa(pixd, pixs, hsize, vsize);
        }

        if (vsize == 1) {
            pixt2 = MorphDwa_1(null, pixs, L.L_MORPH_DILATE, selnameh!);
        } else if (hsize == 1) {
            pixt2 = MorphDwa_1(null, pixs, L.L_MORPH_DILATE, selnamev!);
        } else {
            pixt1 = pixs.AddBorder(32, 0);
            pixt3 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh!);
            FMorphopGen_1(pixt1, pixt3, L.L_MORPH_DILATE, selnamev!);
            pixt2 = pixt1.RemoveBorder(32);
        }

        if (pixd == null)
            return pixt2;

        Pix? pixt = pixt2;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

