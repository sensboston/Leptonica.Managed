/*
 *  morphdwa.c: binary morphological (dwa) ops with brick Sels
 *
 *    Binary morphological (dwa) ops with brick Sels
 *         Pix.DilateBrickDwa()
 *         Pix.ErodeBrickDwa()
 *         Pix.OpenBrickDwa()
 *         Pix.CloseBrickDwa()
 *
 *    Binary composite morphological (dwa) ops with brick Sels
 *         Pix.DilateCompBrickDwa()
 *         Pix.ErodeCompBrickDwa()
 *         Pix.OpenCompBrickDwa()
 *         Pix.CloseCompBrickDwa()
 *
 *    Binary extended composite morphological (dwa) ops with brick Sels
 *         Pix.DilateCompBrickExtendDwa()
 *         Pix.ErodeCompBrickExtendDwa()
 *         Pix.OpenCompBrickExtendDwa()
 *         Pix.CloseCompBrickExtendDwa()
 *         Pix.GetExtendedCompositeParameters()
 *
 *  These are higher-level interfaces for dwa morphology with brick Sels.
 *
 *  If either linear brick Sel is not in the set of 58 generated by Sela.AddBasic(),
 *  the non-composite operations call the associated composite operation.  If either
 *  Sel brick dimension is greater than 63, the extended composite function is called.
 *  The generated dwa code is in Generated/fmorphgen.1.cs (basic Sels) and
 *  Generated/dwacomb.2.cs (comb Sels).
 */
