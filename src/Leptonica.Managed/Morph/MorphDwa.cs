    // leptonica: pixCloseCompBrickExtendDwa (morphdwa.c)
    /// <summary>Closes (safely) with a composite brick Sel of any size, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (2) There is no need to call this directly: pixCloseCompBrickDwa()
    ///     calls this function if either brick dimension exceeds 63.
    /// (3) This is a 'safe' closing; we add an extra border of OFF
    ///     pixels for the standard asymmetric b.c.
    /// </remarks>
    public static Pix CloseCompBrickExtendDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixCloseCompBrickExtendDwa";
        uint bordercolor;
        int borderx, bordery;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");

            /* For "safe closing" with ASYMMETRIC_MORPH_BC, we always need
             * an extra 32 OFF pixels around the image (in addition to
             * the 32 added pixels for all dwa operations), whereas with
             * SYMMETRIC_MORPH_BC this is not necessary. */
        bordercolor = GetMorphBorderPixelColor(L.L_MORPH_ERODE, 1);
        if (bordercolor == 0) {  /* asymmetric b.c. */
            borderx = 32 + (hsize / 64) * 32;
            bordery = 32 + (vsize / 64) * 32;
        } else {  /* symmetric b.c. */
            borderx = bordery = 32;
        }
        pixt1 = pixs.AddBorderGeneral(borderx, borderx, bordery, bordery, 0);

        pixt2 = DilateCompBrickExtendDwa(null, pixt1, hsize, vsize);
        ErodeCompBrickExtendDwa(pixt1, pixt2, hsize, vsize);

        pixt3 = pixt1.RemoveBorderGeneral(borderx, borderx, bordery, bordery);

        if (pixd == null)
            return pixt3;

        Pix? pixt = pixt3;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

    // leptonica: getExtendedCompositeParameters (morphdwa.c)
    /// <summary>Gets the number of 63-sized operations and the size of the extra one.</summary>
    /// <param name="size">of the brick Sel</param>
    /// <param name="pn">number of 63-sized ops (0 if size &lt;= 63)</param>
    /// <param name="pextra">size of the extra op</param>
    public static void GetExtendedCompositeParameters(int size, out int pn, out int pextra)
    {
        int n, extra;

        if (size <= 63) {
            n = 0;
            extra = Math.Min(1, size);
        } else {  /* size > 63 */
            n = 1 + (int)((size - 63) / 62);
            extra = size - 63 - (n - 1) * 62 + 1;
        }

        pn = n;
        pextra = extra;
    }

    // (variant of the above that also returns pactualsize, as the C function does when it is not null)
    /// <summary>Gets the number of 63-sized operations, the size of the extra one and the actual size.</summary>
    /// <param name="size">of the brick Sel</param>
    /// <param name="pn">number of 63-sized ops (0 if size &lt;= 63)</param>
    /// <param name="pextra">size of the extra op</param>
    /// <param name="pactualsize">the size that is actually applied</param>
    public static void GetExtendedCompositeParameters(int size, out int pn, out int pextra,
                                                      out int pactualsize)
    {
        int n, extra, fact1, fact2;

        if (size <= 63) {
            n = 0;
            extra = Math.Min(1, size);
        } else {  /* size > 63 */
            n = 1 + (int)((size - 63) / 62);
            extra = size - 63 - (n - 1) * 62 + 1;
        }

        SelectComposableSizes(extra, out fact1, out fact2);
        pactualsize = 63 + (n - 1) * 62 + fact1 * fact2 - 1;

        pn = n;
        pextra = extra;
    }
