    // leptonica: pixCloseBrickDwa (morphdwa.c)
    /// <summary>Closes (safely) with a brick Sel, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) This is a 'safe' closing; we add an extra border of 32 OFF
    ///     pixels for the standard asymmetric b.c.
    /// (2) These implement 2D brick Sels, using linear Sels generated
    ///     with selaAddBasic().
    /// (3) A brick Sel has hits for all elements.
    /// (4) The origin of the Sel is at (x, y) = (hsize/2, vsize/2)
    /// (5) Do separably if both hsize and vsize are &gt; 1.
    /// (6) It is necessary that both horizontal and vertical Sels
    ///     of the input size are defined in the basic sela.
    /// (7) Note that we must always set or clear the border pixels
    ///     before each operation, depending on the the b.c.
    ///     (symmetric or asymmetric).
    /// (8) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (9) For clarity, if the case is known, use these patterns:
    ///     (a) pixd = Pix.CloseBrickDwa(null, pixs, ...);
    ///     (b) Pix.CloseBrickDwa(pixs, pixs, ...);
    ///     (c) Pix.CloseBrickDwa(pixd, pixs, ...);
    /// (10) The size of the result is determined by pixs.
    /// (11) If either linear Sel is not found, this calls
    ///      the appropriate decomposible function.
    /// </remarks>
    public static Pix CloseBrickDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixCloseBrickDwa";
        uint bordercolor;
        int bordersize;
        bool found;
        string? selnameh, selnamev;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");

        if (hsize == 1 && vsize == 1)
            return Copy(pixd, pixs);

        found = true;
        selnameh = selnamev = null;
        if (hsize > 1) {
            selnameh = BrickNameOrNull(hsize, 1);
            if (selnameh == null) found = false;
        }
        if (vsize > 1) {
            selnamev = BrickNameOrNull(1, vsize);
            if (selnamev == null) found = false;
        }
        if (!found) {
            Log.Info(func, "Calling the decomposable dwa function\n");
            return CloseCompBrickDwa(pixd, pixs, hsize, vsize);
        }

            /* For "safe closing" with ASYMMETRIC_MORPH_BC, we always need
             * an extra 32 OFF pixels around the image (in addition to
             * the 32 added pixels for all dwa operations), whereas with
             * SYMMETRIC_MORPH_BC this is not necessary. */
        bordercolor = GetMorphBorderPixelColor(L.L_MORPH_ERODE, 1);
        if (bordercolor == 0)   /* asymmetric b.c. */
            bordersize = 64;
        else   /* symmetric b.c. */
            bordersize = 32;
        pixt1 = pixs.AddBorder(bordersize, 0);

        if (vsize == 1) {   /* horizontal only */
            pixt2 = FMorphopGen_1(null, pixt1, L.L_MORPH_CLOSE, selnameh!);
        } else if (hsize == 1) {   /* vertical only */
            pixt2 = FMorphopGen_1(null, pixt1, L.L_MORPH_CLOSE, selnamev!);
        } else {  /* do separable */
            pixt3 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh!);
            pixt2 = FMorphopGen_1(null, pixt3, L.L_MORPH_DILATE, selnamev!);
            FMorphopGen_1(pixt3, pixt2, L.L_MORPH_ERODE, selnameh!);
            FMorphopGen_1(pixt2, pixt3, L.L_MORPH_ERODE, selnamev!);
        }
        pixt3 = pixt2.RemoveBorder(bordersize);

        if (pixd == null)
            return pixt3;

        Pix? pixt = pixt3;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

