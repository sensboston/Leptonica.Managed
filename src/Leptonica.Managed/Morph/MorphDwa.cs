    // leptonica: pixDilateCompBrickExtendDwa (morphdwa.c)
    /// <summary>Dilates with a composite brick Sel of any size, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (2) There is no need to call this directly: pixDilateCompBrickDwa()
    ///     calls this function if either brick dimension exceeds 63.
    /// (3) The Sel is applied as a sequence of operations with size 63
    ///     and, if needed, one with a smaller size; the net result is
    ///     correct in length to within 2 pixels.
    /// </remarks>
    public static Pix DilateCompBrickExtendDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixDilateCompBrickExtendDwa";
        int i, nops, nh = 0, extrah = 0, nv = 0, extrav = 0;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");

        if (hsize < 64 && vsize < 64)
            return DilateCompBrickDwa(pixd, pixs, hsize, vsize);

        if (hsize > 63)
            GetExtendedCompositeParameters(hsize, out nh, out extrah);
        if (vsize > 63)
            GetExtendedCompositeParameters(vsize, out nv, out extrav);

            /* Horizontal dilation first: pixs --> pixt2.  Do not alter pixs. */
        pixt1 = CreateTemplate(pixs);  /* temp image */
        if (hsize == 1) {
            pixt2 = Clone(pixs);
        } else if (hsize < 64) {
            pixt2 = DilateCompBrickDwa(null, pixs, hsize, 1);
        } else if (hsize == 64) {  /* approximate */
            pixt2 = DilateCompBrickDwa(null, pixs, 63, 1);
        } else {
            nops = (extrah < 3) ? nh : nh + 1;
            if ((nops & 1) != 0) {  /* odd */
                if (extrah > 2)
                    pixt2 = DilateCompBrickDwa(null, pixs, extrah, 1);
                else
                    pixt2 = DilateCompBrickDwa(null, pixs, 63, 1);
                for (i = 0; i < nops / 2; i++) {
                    DilateCompBrickDwa(pixt1, pixt2, 63, 1);
                    DilateCompBrickDwa(pixt2, pixt1, 63, 1);
                }
            } else {  /* nops even */
                if (extrah > 2) {
                    DilateCompBrickDwa(pixt1, pixs, extrah, 1);
                    pixt2 = DilateCompBrickDwa(null, pixt1, 63, 1);
                } else {  /* they're all 63s */
                    DilateCompBrickDwa(pixt1, pixs, 63, 1);
                    pixt2 = DilateCompBrickDwa(null, pixt1, 63, 1);
                }
                for (i = 0; i < nops / 2 - 1; i++) {
                    DilateCompBrickDwa(pixt1, pixt2, 63, 1);
                    DilateCompBrickDwa(pixt2, pixt1, 63, 1);
                }
            }
        }

            /* Vertical dilation: pixt2 --> pixt3.  */
        if (vsize == 1) {
            pixt3 = Clone(pixt2);
        } else if (vsize < 64) {
            pixt3 = DilateCompBrickDwa(null, pixt2, 1, vsize);
        } else if (vsize == 64) {  /* approximate */
            pixt3 = DilateCompBrickDwa(null, pixt2, 1, 63);
        } else {
            nops = (extrav < 3) ? nv : nv + 1;
            if ((nops & 1) != 0) {  /* odd */
                if (extrav > 2)
                    pixt3 = DilateCompBrickDwa(null, pixt2, 1, extrav);
                else
                    pixt3 = DilateCompBrickDwa(null, pixt2, 1, 63);
                for (i = 0; i < nops / 2; i++) {
                    DilateCompBrickDwa(pixt1, pixt3, 1, 63);
                    DilateCompBrickDwa(pixt3, pixt1, 1, 63);
                }
            } else {  /* nops even */
                if (extrav > 2) {
                    DilateCompBrickDwa(pixt1, pixt2, 1, extrav);
                    pixt3 = DilateCompBrickDwa(null, pixt1, 1, 63);
                } else {  /* they're all 63s */
                    DilateCompBrickDwa(pixt1, pixt2, 1, 63);
                    pixt3 = DilateCompBrickDwa(null, pixt1, 1, 63);
                }
                for (i = 0; i < nops / 2 - 1; i++) {
                    DilateCompBrickDwa(pixt1, pixt3, 1, 63);
                    DilateCompBrickDwa(pixt3, pixt1, 1, 63);
                }
            }
        }

        if (pixd == null)
            return pixt3;

        Pix? pixt = pixt3;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

    // leptonica: pixErodeCompBrickExtendDwa (morphdwa.c)
    /// <summary>Erodes with a composite brick Sel of any size, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (2) There is no need to call this directly: pixErodeCompBrickDwa()
    ///     calls this function if either brick dimension exceeds 63.
    /// (3) The Sel is applied as a sequence of operations with size 63
    ///     and, if needed, one with a smaller size; the net result is
    ///     correct in length to within 2 pixels.
    /// </remarks>
    public static Pix ErodeCompBrickExtendDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixErodeCompBrickExtendDwa";
        int i, nops, nh = 0, extrah = 0, nv = 0, extrav = 0;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");

        if (hsize < 64 && vsize < 64)
            return ErodeCompBrickDwa(pixd, pixs, hsize, vsize);

        if (hsize > 63)
            GetExtendedCompositeParameters(hsize, out nh, out extrah);
        if (vsize > 63)
            GetExtendedCompositeParameters(vsize, out nv, out extrav);

            /* Horizontal erosion first: pixs --> pixt2.  Do not alter pixs. */
        pixt1 = CreateTemplate(pixs);  /* temp image */
        if (hsize == 1) {
            pixt2 = Clone(pixs);
        } else if (hsize < 64) {
            pixt2 = ErodeCompBrickDwa(null, pixs, hsize, 1);
        } else if (hsize == 64) {  /* approximate */
            pixt2 = ErodeCompBrickDwa(null, pixs, 63, 1);
        } else {
            nops = (extrah < 3) ? nh : nh + 1;
            if ((nops & 1) != 0) {  /* odd */
                if (extrah > 2)
                    pixt2 = ErodeCompBrickDwa(null, pixs, extrah, 1);
                else
                    pixt2 = ErodeCompBrickDwa(null, pixs, 63, 1);
                for (i = 0; i < nops / 2; i++) {
                    ErodeCompBrickDwa(pixt1, pixt2, 63, 1);
                    ErodeCompBrickDwa(pixt2, pixt1, 63, 1);
                }
            } else {  /* nops even */
                if (extrah > 2) {
                    ErodeCompBrickDwa(pixt1, pixs, extrah, 1);
                    pixt2 = ErodeCompBrickDwa(null, pixt1, 63, 1);
                } else {  /* they're all 63s */
                    ErodeCompBrickDwa(pixt1, pixs, 63, 1);
                    pixt2 = ErodeCompBrickDwa(null, pixt1, 63, 1);
                }
                for (i = 0; i < nops / 2 - 1; i++) {
                    ErodeCompBrickDwa(pixt1, pixt2, 63, 1);
                    ErodeCompBrickDwa(pixt2, pixt1, 63, 1);
                }
            }
        }

            /* Vertical erosion: pixt2 --> pixt3.  */
        if (vsize == 1) {
            pixt3 = Clone(pixt2);
        } else if (vsize < 64) {
            pixt3 = ErodeCompBrickDwa(null, pixt2, 1, vsize);
        } else if (vsize == 64) {  /* approximate */
            pixt3 = ErodeCompBrickDwa(null, pixt2, 1, 63);
        } else {
            nops = (extrav < 3) ? nv : nv + 1;
            if ((nops & 1) != 0) {  /* odd */
                if (extrav > 2)
                    pixt3 = ErodeCompBrickDwa(null, pixt2, 1, extrav);
                else
                    pixt3 = ErodeCompBrickDwa(null, pixt2, 1, 63);
                for (i = 0; i < nops / 2; i++) {
                    ErodeCompBrickDwa(pixt1, pixt3, 1, 63);
                    ErodeCompBrickDwa(pixt3, pixt1, 1, 63);
                }
            } else {  /* nops even */
                if (extrav > 2) {
                    ErodeCompBrickDwa(pixt1, pixt2, 1, extrav);
                    pixt3 = ErodeCompBrickDwa(null, pixt1, 1, 63);
                } else {  /* they're all 63s */
                    ErodeCompBrickDwa(pixt1, pixt2, 1, 63);
                    pixt3 = ErodeCompBrickDwa(null, pixt1, 1, 63);
                }
                for (i = 0; i < nops / 2 - 1; i++) {
                    ErodeCompBrickDwa(pixt1, pixt3, 1, 63);
                    ErodeCompBrickDwa(pixt3, pixt1, 1, 63);
                }
            }
        }

        if (pixd == null)
            return pixt3;

        Pix? pixt = pixt3;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

