    // leptonica: pixDilateCompBrickDwa (morphdwa.c)
    /// <summary>Dilates with a composite brick Sel, using dwa.</summary>
    /// <param name="pixd">[optional]; this can be null, equal to pixs, or different from pixs</param>
    /// <param name="pixs">1 bpp</param>
    /// <param name="hsize">width of brick Sel</param>
    /// <param name="vsize">height of brick Sel</param>
    /// <returns>pixd</returns>
    /// <remarks>
    /// (1) These implement a separable composite dilation with 2D brick Sels.
    /// (2) For efficiency, it may decompose each linear morphological
    ///     operation into two (brick + comb).
    /// (3) A brick Sel has hits for all elements.
    /// (4) The origin of the Sel is at (x, y) = (hsize/2, vsize/2)
    /// (5) Do separably if both hsize and vsize are &gt; 1.
    /// (6) It is necessary that both horizontal and vertical Sels
    ///     of the input size are defined in the basic sela.
    /// (7) There are three cases:
    ///     (a) pixd == null   (result into new pixd)
    ///     (b) pixd == pixs   (in-place; writes result back to pixs)
    ///     (c) pixd != pixs   (puts result into existing pixd)
    /// (8) For clarity, if the case is known, use these patterns:
    ///     (a) pixd = Pix.DilateCompBrickDwa(null, pixs, ...);
    ///     (b) Pix.DilateCompBrickDwa(pixs, pixs, ...);
    ///     (c) Pix.DilateCompBrickDwa(pixd, pixs, ...);
    /// (9) The size of pixd is determined by pixs.
    /// (10) CAUTION: both hsize and vsize are being decomposed.
    ///     The decomposer chooses a product of sizes (call them
    ///     'terms') for each that is close to the input size,
    ///     but not necessarily equal to it.  It attempts to optimize:
    ///        (a) for consistency with the input values: the product
    ///            of terms is close to the input size
    ///        (b) for efficiency of the operation: the sum of the
    ///            terms is small; ideally about twice the square
    ///            root of the input size.
    ///     So, for example, if the input hsize = 37, which is
    ///     a prime number, the decomposer will break this into two
    ///     terms, 6 and 6, so that the net result is a dilation
    ///     with hsize = 36.
    /// </remarks>
    public static Pix DilateCompBrickDwa(Pix? pixd, Pix pixs, int hsize, int vsize)
    {
        const string func = "pixDilateCompBrickDwa";
        string? selnameh1, selnameh2, selnamev1, selnamev2;
        int hsize1, hsize2, vsize1, vsize2;
        Pix pixt1, pixt2, pixt3;

        if (pixs.Depth != 1)
            throw Lept.Arg(func, "pixs not 1 bpp");
        if (hsize < 1 || vsize < 1)
            throw Lept.Arg(func, "hsize and vsize not >= 1");
        if (hsize > 63 || vsize > 63)
            return DilateCompBrickExtendDwa(pixd, pixs, hsize, vsize);

        if (hsize == 1 && vsize == 1)
            return Copy(pixd, pixs);

        hsize1 = hsize2 = vsize1 = vsize2 = 1;
        selnameh1 = selnameh2 = selnamev1 = selnamev2 = null;
        if (hsize > 1)
            Sel.GetCompositeParameters(hsize, out hsize1, out hsize2, out selnameh1,
                                       out selnameh2, out _, out _);
        if (vsize > 1)
            Sel.GetCompositeParameters(vsize, out vsize1, out vsize2, out _, out _,
                                       out selnamev1, out selnamev2);

        if (DEBUG_SEL_LOOKUP) {
            Console.Error.WriteLine($"nameh1={selnameh1}, nameh2={selnameh2}, namev1={selnamev1}, namev2={selnamev2}");
            Console.Error.WriteLine($"hsize1={hsize1}, hsize2={hsize2}, vsize1={vsize1}, vsize2={vsize2}");
        }

        pixt1 = pixs.AddBorder(64, 0);
        if (vsize == 1) {
            if (hsize2 == 1) {
                pixt2 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh1!);
            } else {
                pixt3 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh1!);
                pixt2 = FMorphopGen_2(null, pixt3, L.L_MORPH_DILATE, selnameh2!);
            }
        } else if (hsize == 1) {
            if (vsize2 == 1) {
                pixt2 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnamev1!);
            } else {
                pixt3 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnamev1!);
                pixt2 = FMorphopGen_2(null, pixt3, L.L_MORPH_DILATE, selnamev2!);
            }
        } else {  /* vsize and hsize both > 1 */
            if (hsize2 == 1) {
                pixt3 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh1!);
            } else {
                pixt2 = FMorphopGen_1(null, pixt1, L.L_MORPH_DILATE, selnameh1!);
                pixt3 = FMorphopGen_2(null, pixt2, L.L_MORPH_DILATE, selnameh2!);
            }
            if (vsize2 == 1) {
                pixt2 = FMorphopGen_1(null, pixt3, L.L_MORPH_DILATE, selnamev1!);
            } else {
                pixt2 = FMorphopGen_1(null, pixt3, L.L_MORPH_DILATE, selnamev1!);
                FMorphopGen_2(pixt2, pixt2, L.L_MORPH_DILATE, selnamev2!);
            }
        }
        pixt1 = pixt2.RemoveBorder(64);

        if (pixd == null)
            return pixt1;

        Pix? pixt = pixt1;
        pixd.TransferAllData(ref pixt, false, false);
        return pixd;
    }

