using System;

namespace Leptonica;

/*
 *  quadtree.c: Quadtree statistics of an image.
 *
 *      Top level quadtree linear statistics
 *            Pix.QuadtreeMean
 *            Pix.QuadtreeVariance
 *
 *      Statistics in an arbitrary rectangle
 *            Pix.MeanInRectangle
 *            Pix.VarianceInRectangle
 *
 *      Quadtree regions
 *            Boxaa.QuadtreeRegions
 *
 *      Quadtree access
 *            Pix.QuadtreeGetParent
 *            Pix.QuadtreeGetChildren
 *            Pix.QuadtreeMaxLevels
 *
 *      Display quadtree
 *            FPixa.DisplayQuadtree
 *
 *  There are many other statistical quantities that can be computed
 *  in a quadtree, such as rank values, and these can be added as
 *  the need arises.
 *
 *  Similar results that can approximate a single level of the quadtree
 *  can be generated by pixGetAverageTiled().  There we specify the
 *  tile size over which the mean, mean square, and root variance
 *  are generated; the results are saved in a (reduced size) pix.
 *  Because the tile dimensions are integers, it is usually not possible
 *  to obtain tilings that are a power of 2, as required for quadtrees.
 *
 *  Notes on the port:
 *    - The static quadtree functions are static methods of Pix, the primary
 *      class of this file.
 *    - quadtreeGetParent() and quadtreeGetChildren() return false (with the
 *      values 0.0) when the level or the coordinates are invalid, like the
 *      return code 1 of the C functions.
 */

public sealed partial class Pix
{
    /*----------------------------------------------------------------------*
     *                  Top-level quadtree linear statistics                *
     *----------------------------------------------------------------------*/
    // leptonica: pixQuadtreeMean (quadtree.c)
    /// <summary>Mean values in the regions of each level of a quadtree.</summary>
    /// <param name="nlevels">in quadtree; max allowed depends on image size</param>
    /// <param name="pix_ma">input mean accumulator; can be null</param>
    /// <returns>mean values in quadtree</returns>
    /// <remarks>
    /// (1) The returned fpixa has %nlevels of fpix, each containing
    ///     the mean values at its level.  Level 0 has a
    ///     single value; level 1 has 4 values; level 2 has 16; etc.
    /// </remarks>
    public FPixa QuadtreeMean(int nlevels, Pix? pix_ma)
    {
        const string func = "pixQuadtreeMean";
        int i, j, w, h, size, n;
        float val;
        Box box;
        Boxa boxa;
        Boxaa baa;
        FPix fpix;
        Pix pix_mac;
        FPixa fpixa;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        GetDimensions(out w, out h, out _);
        if (nlevels > QuadtreeMaxLevels(w, h))
            throw Lept.Arg(func, "nlevels too large for image");

        if (pix_ma == null)
            pix_mac = BlockconvAccum();
        else
            pix_mac = Clone(pix_ma);

        baa = Boxaa.QuadtreeRegions(w, h, nlevels);

        fpixa = FPixa.Create(nlevels);
        for (i = 0; i < nlevels; i++) {
            boxa = baa.GetBoxa(i, L.L_CLONE);
            size = 1 << i;
            n = boxa.Count;  /* n == size * size */
            fpix = FPix.Create(size, size);
            for (j = 0; j < n; j++) {
                box = boxa.GetBox(j, L.L_CLONE);
                val = MeanInRectangle(box, pix_mac);
                fpix.SetPixel(j % size, j / size, val);
            }
            fpixa.AddFPix(fpix, L.L_INSERT);
        }

        return fpixa;
    }

    // leptonica: pixQuadtreeVariance (quadtree.c)
    /// <summary>Variance and root variance in the regions of each level of a quadtree.</summary>
    /// <param name="nlevels">in quadtree</param>
    /// <param name="pix_ma">input mean accumulator; can be null</param>
    /// <param name="dpix_msa">input mean square accumulator; can be null</param>
    /// <param name="pfpixa_v">variance values in quadtree</param>
    /// <param name="pfpixa_rv">root variance values in quadtree</param>
    /// <remarks>
    /// (1) The returned fpixav and fpixarv have %nlevels of fpix,
    ///     each containing at the respective levels the variance
    ///     and root variance values.
    /// </remarks>
    public void QuadtreeVariance(int nlevels, Pix? pix_ma, DPix? dpix_msa,
                                 out FPixa pfpixa_v, out FPixa pfpixa_rv)
    {
        const string func = "pixQuadtreeVariance";
        int i, j, w, h, size, n;
        float var, rvar;
        Box box;
        Boxa boxa;
        Boxaa baa;
        FPix fpixv, fpixrv;
        Pix pix_mac;     /* copy of mean accumulator */
        DPix dpix_msac;  /* msa clone */

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined or not 8 bpp");
        GetDimensions(out w, out h, out _);
        if (nlevels > QuadtreeMaxLevels(w, h))
            throw Lept.Arg(func, "nlevels too large for image");

        if (pix_ma == null)
            pix_mac = BlockconvAccum();
        else
            pix_mac = Clone(pix_ma);
        if (dpix_msa == null)
            dpix_msac = MeanSquareAccum();
        else
            dpix_msac = dpix_msa.Clone();

        baa = Boxaa.QuadtreeRegions(w, h, nlevels);

        pfpixa_v = FPixa.Create(nlevels);
        pfpixa_rv = FPixa.Create(nlevels);
        for (i = 0; i < nlevels; i++) {
            boxa = baa.GetBoxa(i, L.L_CLONE);
            size = 1 << i;
            n = boxa.Count;  /* n == size * size */
            fpixv = FPix.Create(size, size);
            fpixrv = FPix.Create(size, size);
            for (j = 0; j < n; j++) {
                box = boxa.GetBox(j, L.L_CLONE);
                VarianceInRectangle(box, pix_mac, dpix_msac, out var, out rvar);
                fpixv.SetPixel(j % size, j / size, var);
                fpixrv.SetPixel(j % size, j / size, rvar);
            }
            pfpixa_v.AddFPix(fpixv, L.L_INSERT);
            pfpixa_rv.AddFPix(fpixrv, L.L_INSERT);
        }
    }

    /*----------------------------------------------------------------------*
     *                  Statistics in an arbitrary rectangle                *
     *----------------------------------------------------------------------*/
    // leptonica: pixMeanInRectangle (quadtree.c)
    /// <summary>Mean value in a rectangle, using the mean accumulator.</summary>
    /// <param name="box">region to compute mean value</param>
    /// <param name="pixma">mean accumulator</param>
    /// <returns>mean value</returns>
    /// <remarks>
    /// (1) This function is intended to be used for many rectangles
    ///     on the same image.  It can find the mean within a
    ///     rectangle in O(1), independent of the size of the rectangle.
    /// </remarks>
    public float MeanInRectangle(Box box, Pix pixma)
    {
        const string func = "pixMeanInRectangle";
        int w, h, bx, by, bw, bh;
        uint val00, val01, val10, val11;
        float norm;
        Box? boxc;
        float pval;

        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined");

            /* Clip rectangle to image */
        GetDimensions(out w, out h, out _);
        boxc = box.ClipToRectangleOrNull(w, h);
        bx = by = bw = bh = 0;
        boxc?.GetGeometry(out bx, out by, out bw, out bh);

        if (bw == 0 || bh == 0)
            throw Lept.Arg(func, "no pixels in box");

            /* Use up to 4 points in the accumulator */
        norm = 1.0f / ((float)(bw) * bh);
        if (bx > 0 && by > 0) {
            pixma.GetPixel(bx + bw - 1, by + bh - 1, out val11);
            pixma.GetPixel(bx + bw - 1, by - 1, out val10);
            pixma.GetPixel(bx - 1, by + bh - 1, out val01);
            pixma.GetPixel(bx - 1, by - 1, out val00);
            pval = norm * unchecked(val11 - val01 + val00 - val10);
        } else if (by > 0) {  /* bx == 0 */
            pixma.GetPixel(bw - 1, by + bh - 1, out val11);
            pixma.GetPixel(bw - 1, by - 1, out val10);
            pval = norm * unchecked(val11 - val10);
        } else if (bx > 0) {  /* by == 0 */
            pixma.GetPixel(bx + bw - 1, bh - 1, out val11);
            pixma.GetPixel(bx - 1, bh - 1, out val01);
            pval = norm * unchecked(val11 - val01);
        } else {  /* bx == 0 && by == 0 */
            pixma.GetPixel(bw - 1, bh - 1, out val11);
            pval = norm * val11;
        }

        return pval;
    }

    // leptonica: pixVarianceInRectangle (quadtree.c)
    /// <summary>Variance and root variance in a rectangle, using the mean and mean square accumulators.</summary>
    /// <param name="box">region to compute variance and/or root variance</param>
    /// <param name="pix_ma">mean accumulator</param>
    /// <param name="dpix_msa">mean square accumulator</param>
    /// <param name="pvar">variance</param>
    /// <param name="prvar">root variance</param>
    /// <remarks>
    /// (1) This function is intended to be used for many rectangles
    ///     on the same image.  It can find the variance and/or the
    ///     square root of the variance within a rectangle in O(1),
    ///     independent of the size of the rectangle.
    /// </remarks>
    public void VarianceInRectangle(Box box, Pix pix_ma, DPix dpix_msa,
                                    out float pvar, out float prvar)
    {
        const string func = "pixVarianceInRectangle";
        int w, h, bx, by, bw, bh;
        uint val00, val01, val10, val11;
        double dval00, dval01, dval10, dval11, mval, msval, var, norm;
        Box? boxc;

        pvar = prvar = 0.0f;
        if (Depth != 8)
            throw Lept.Arg(func, "pixs not defined");

            /* Clip rectangle to image */
        GetDimensions(out w, out h, out _);
        boxc = box.ClipToRectangleOrNull(w, h);
        bx = by = bw = bh = 0;
        boxc?.GetGeometry(out bx, out by, out bw, out bh);

        if (bw == 0 || bh == 0)
            throw Lept.Arg(func, "no pixels in box");

            /* Use up to 4 points in the accumulators */
        norm = 1.0 / ((float)(bw) * bh);
        if (bx > 0 && by > 0) {
            pix_ma.GetPixel(bx + bw - 1, by + bh - 1, out val11);
            pix_ma.GetPixel(bx + bw - 1, by - 1, out val10);
            pix_ma.GetPixel(bx - 1, by + bh - 1, out val01);
            pix_ma.GetPixel(bx - 1, by - 1, out val00);
            dpix_msa.GetPixel(bx + bw - 1, by + bh - 1, out dval11);
            dpix_msa.GetPixel(bx + bw - 1, by - 1, out dval10);
            dpix_msa.GetPixel(bx - 1, by + bh - 1, out dval01);
            dpix_msa.GetPixel(bx - 1, by - 1, out dval00);
            mval = norm * unchecked(val11 - val01 + val00 - val10);
            msval = norm * (dval11 - dval01 + dval00 - dval10);
            var = (msval - mval * mval);
            pvar = (float)var;
            prvar = (float)(Math.Sqrt(var));
        } else if (by > 0) {  /* bx == 0 */
            pix_ma.GetPixel(bw - 1, by + bh - 1, out val11);
            pix_ma.GetPixel(bw - 1, by - 1, out val10);
            dpix_msa.GetPixel(bw - 1, by + bh - 1, out dval11);
            dpix_msa.GetPixel(bw - 1, by - 1, out dval10);
            mval = norm * unchecked(val11 - val10);
            msval = norm * (dval11 - dval10);
            var = (msval - mval * mval);
            pvar = (float)var;
            prvar = (float)(Math.Sqrt(var));
        } else if (bx > 0) {  /* by == 0 */
            pix_ma.GetPixel(bx + bw - 1, bh - 1, out val11);
            pix_ma.GetPixel(bx - 1, bh - 1, out val01);
            dpix_msa.GetPixel(bx + bw - 1, bh - 1, out dval11);
            dpix_msa.GetPixel(bx - 1, bh - 1, out dval01);
            mval = norm * unchecked(val11 - val01);
            msval = norm * (dval11 - dval01);
            var = (msval - mval * mval);
            pvar = (float)var;
            prvar = (float)(Math.Sqrt(var));
        } else {  /* bx == 0 && by == 0 */
            pix_ma.GetPixel(bw - 1, bh - 1, out val11);
            dpix_msa.GetPixel(bw - 1, bh - 1, out dval11);
            mval = norm * val11;
            msval = norm * dval11;
            var = (msval - mval * mval);
            pvar = (float)var;
            prvar = (float)(Math.Sqrt(var));
        }
    }

    /*----------------------------------------------------------------------*
     *                            Quadtree access                           *
     *----------------------------------------------------------------------*/
    // leptonica: quadtreeGetParent (quadtree.c)
    /// <summary>Value of the parent of a pixel in the quadtree.</summary>
    /// <param name="fpixa">mean, variance or root variance</param>
    /// <param name="level">of current pixel</param>
    /// <param name="x">of current pixel</param>
    /// <param name="y">of current pixel</param>
    /// <param name="pval">parent pixel value, or 0.0 on error</param>
    /// <returns>true if OK; false if the level or the coordinates are invalid</returns>
    /// <remarks>
    /// (1) Check return value for error.  On error, val is returned as 0.0.
    /// (2) The parent is located at:
    ///        level - 1
    ///        (x/2, y/2)
    /// </remarks>
    public static bool QuadtreeGetParent(FPixa fpixa, int level, int x, int y, out float pval)
    {
        const string func = "quadtreeGetParent";
        int n;

        pval = 0.0f;
        n = fpixa.Count;
        if (level < 1 || level >= n) {
            Log.Error(func, "invalid level");
            return false;
        }

        if (!fpixa.GetPixel(level - 1, x / 2, y / 2, out pval)) {
            Log.Error(func, "invalid coordinates");
            return false;
        }
        return true;
    }

    // leptonica: quadtreeGetChildren (quadtree.c)
    /// <summary>Values of the four children of a pixel in the quadtree.</summary>
    /// <param name="fpixa">mean, variance or root variance</param>
    /// <param name="level">of current pixel</param>
    /// <param name="x">of current pixel</param>
    /// <param name="y">of current pixel</param>
    /// <param name="pval00">child pixel value at (2x, 2y)</param>
    /// <param name="pval10">child pixel value at (2x+1, 2y)</param>
    /// <param name="pval01">child pixel value at (2x, 2y+1)</param>
    /// <param name="pval11">child pixel value at (2x+1, 2y+1)</param>
    /// <returns>true if OK; false if the level or the coordinates are invalid</returns>
    /// <remarks>
    /// (1) Check return value for error.  On error, all return vals are 0.0.
    /// (2) The returned child pixels are located at:
    ///        level + 1
    ///        (2x, 2y), (2x+1, 2y), (2x, 2y+1), (2x+1, 2y+1)
    /// </remarks>
    public static bool QuadtreeGetChildren(FPixa fpixa, int level, int x, int y,
                                           out float pval00, out float pval10,
                                           out float pval01, out float pval11)
    {
        const string func = "quadtreeGetChildren";
        int n;

        pval00 = pval10 = pval01 = pval11 = 0.0f;
        n = fpixa.Count;
        if (level < 0 || level >= n - 1) {
            Log.Error(func, "invalid level");
            return false;
        }

        if (!fpixa.GetPixel(level + 1, 2 * x, 2 * y, out pval00)) {
            Log.Error(func, "invalid coordinates");
            return false;
        }
        fpixa.GetPixel(level + 1, 2 * x + 1, 2 * y, out pval10);
        fpixa.GetPixel(level + 1, 2 * x, 2 * y + 1, out pval01);
        fpixa.GetPixel(level + 1, 2 * x + 1, 2 * y + 1, out pval11);
        return true;
    }

    // leptonica: quadtreeMaxLevels (quadtree.c)
    /// <summary>Maximum number of levels of a quadtree of an image.</summary>
    /// <param name="w">dimensions of image</param>
    /// <param name="h">dimensions of image</param>
    /// <returns>maxlevels maximum number of levels allowed, or -1 on error</returns>
    /// <remarks>
    /// (1) The criterion for maxlevels is that the subdivision not
    ///     go down below the single pixel level.  The 1.5 factor
    ///     is intended to keep any rectangle from accidentally
    ///     having zero dimension due to integer truncation.
    /// </remarks>
    public static int QuadtreeMaxLevels(int w, int h)
    {
        int i, minside;

        minside = Math.Min(w, h);
        for (i = 0; i < 20; i++) {  /* 2^10 = one million */
            if (minside < (1.5 * (1 << i)))
                return i - 1;
        }

        return -1;  /* fail if the image has over a trillion pixels! */
    }
}

public sealed partial class Boxaa
{
    /*----------------------------------------------------------------------*
     *                            Quadtree regions                          *
     *----------------------------------------------------------------------*/
    // leptonica: boxaaQuadtreeRegions (quadtree.c)
    /// <summary>The rectangles of each level of a quadtree of an image of a given size.</summary>
    /// <param name="w">size of pix that is being quadtree-ized</param>
    /// <param name="h">size of pix that is being quadtree-ized</param>
    /// <param name="nlevels">number of levels in quadtree</param>
    /// <returns>baa for quadtree regions at each level</returns>
    /// <remarks>
    /// (1) The returned boxaa has %nlevels of boxa, each containing
    ///     the set of rectangles at that level.  The rectangle at
    ///     level 0 is the entire region; at level 1 the region is
    ///     divided into 4 rectangles, and at level n there are n^4
    ///     rectangles.
    /// (2) At each level, the rectangles in the boxa are in "raster"
    ///     order, with LR (fast scan) and TB (slow scan).
    /// </remarks>
    public static Boxaa QuadtreeRegions(int w, int h, int nlevels)
    {
        const string func = "boxaaQuadtreeRegions";
        int i, j, k, maxpts, nside, nbox, bw, bh;
        int[] xstart, xend, ystart, yend;
        Box box;
        Boxa boxa;
        Boxaa baa;

        if (nlevels < 1)
            throw Lept.Arg(func, "nlevels must be >= 1");
        if (w < (1 << (nlevels - 1)))
            throw Lept.Arg(func, "w doesn't support nlevels");
        if (h < (1 << (nlevels - 1)))
            throw Lept.Arg(func, "h doesn't support nlevels");

        baa = Create(nlevels);
        maxpts = 1 << (nlevels - 1);
        xstart = new int[maxpts];
        xend = new int[maxpts];
        ystart = new int[maxpts];
        yend = new int[maxpts];
        for (k = 0; k < nlevels; k++) {
            nside = 1 << k;  /* number of boxes in each direction */
            for (i = 0; i < nside; i++) {
                xstart[i] = (w - 1) * i / nside;
                if (i > 0) xstart[i]++;
                xend[i] = (w - 1) * (i + 1) / nside;
                ystart[i] = (h - 1) * i / nside;
                if (i > 0) ystart[i]++;
                yend[i] = (h - 1) * (i + 1) / nside;
            }
            nbox = 1 << (2 * k);
            boxa = Boxa.Create(nbox);
            for (i = 0; i < nside; i++) {
                bh = yend[i] - ystart[i] + 1;
                for (j = 0; j < nside; j++) {
                    bw = xend[j] - xstart[j] + 1;
                    box = Box.Create(xstart[j], ystart[i], bw, bh);
                    boxa.AddBox(box, L.L_INSERT);
                }
            }
            baa.AddBoxa(boxa, L.L_INSERT);
        }

        return baa;
    }
}

public sealed partial class FPixa
{
    /*----------------------------------------------------------------------*
     *                            Display quadtree                          *
     *----------------------------------------------------------------------*/
    // leptonica: fpixaDisplayQuadtree (quadtree.c)
    /// <summary>Displays the levels of a quadtree as a mosaic of images.</summary>
    /// <param name="factor">replication factor at lowest level</param>
    /// <param name="fontsize">4, ... 20</param>
    /// <returns>pixd 8 bpp, mosaic of quadtree images</returns>
    /// <remarks>
    /// (1) The mean and root variance fall naturally in the 8 bpp range,
    ///     but the variance is typically outside the range.  This
    ///     function displays 8 bpp pix clipped to 255, so the image
    ///     pixels will mostly be 255 (white).
    /// </remarks>
    public Pix DisplayQuadtree(int factor, int fontsize)
    {
        const string func = "fpixaDisplayQuadtree";
        string buf;
        int nlevels, i, mag, w;
        L_Bmf bmf;
        FPix fpix;
        Pix pixt1, pixt2, pixt3, pixt4 = null!, pixd;
        Pixa pixat;

        if ((nlevels = Count) == 0)
            throw Lept.Arg(func, "pixas empty");

        bmf = L_Bmf.Create(null, fontsize);
        pixat = Pixa.Create(nlevels);
        for (i = 0; i < nlevels; i++) {
            fpix = GetFPix(i, L.L_CLONE);
            pixt1 = fpix.ConvertToPix(8, L.L_CLIP_TO_ZERO, 0);
            mag = factor * (1 << (nlevels - i - 1));
            pixt2 = pixt1.ExpandReplicate(mag);
            pixt3 = pixt2.ConvertTo32();
            buf = $"Level {i}\n";
            pixt4 = pixt3.AddSingleTextblock(bmf, buf, 0xff000000, L.L_ADD_BELOW, out _);
            pixat.AddPix(pixt4, L.L_INSERT);
        }
        w = pixt4.Width;
        pixd = pixat.DisplayTiledInRows(32, nlevels * (w + 80), 1.0f, 0, 30, 2);

        return pixd;
    }
}
