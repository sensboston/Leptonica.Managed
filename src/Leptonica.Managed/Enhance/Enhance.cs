    /*-------------------------------------------------------------*
     *                     Histogram equalization                  *
     *-------------------------------------------------------------*/
    // leptonica: pixEqualizeTRC (enhance.c)
    /// <summary>Histogram equalization of a 8 bpp gray, 32 bpp rgb or colormapped image.</summary>
    /// <param name="pixd">[optional] null or equal to pixs</param>
    /// <param name="pixs">8 bpp gray, 32 bpp rgb, or colormapped</param>
    /// <param name="fract">fraction of equalization movement of pixel values</param>
    /// <param name="factor">subsampling factor; integer &gt;= 1</param>
    /// <remarks>
    /// (1) pixd must either be null or equal to pixs.
    ///     For in-place operation, set pixd == pixs:
    ///        pixEqualizeTRC(pixs, pixs, ...);
    ///     To get a new image, set pixd == null:
    ///        pixd = pixEqualizeTRC(NULL, pixs, ...);
    /// (2) In histogram equalization, a tone reproduction curve
    ///     mapping is used to make the number of pixels at each
    ///     intensity equal.
    /// (3) If fract == 0.0, no equalization is performed; return a copy
    ///     unless in-place, in which case this is a no-op.
    ///     If fract == 1.0, equalization is complete.
    /// (4) Set the subsampling factor &gt; 1 to reduce the amount of computation.
    /// (5) If pixs is colormapped, the colormap is removed and
    ///     converted to rgb or grayscale.
    /// (6) If pixs has color, equalization is done in each channel
    ///     separately.
    /// (7) Note that even if there is a colormap, we can get an
    ///     in-place operation because the intermediate image pixt
    ///     is copied back to pixs (which for in-place is the same
    ///     as pixd).
    /// </remarks>
    public static Pix EqualizeTRC(Pix? pixd, Pix pixs, float fract, int factor)
    {
        const string func = "pixEqualizeTRC";

        if (pixd != null && pixd != pixs)
            throw Lept.Arg(func, "pixd not null or pixs");
        PixColormap? cmap = pixs.Colormap;
        int d = pixs.Depth;
        if (d != 8 && d != 32 && cmap == null)
            throw Lept.Arg(func, "pixs not 8/32 bpp or cmapped");
        if (fract < 0.0 || fract > 1.0)
            throw Lept.Arg(func, "fract not in [0.0 ... 1.0]");
        if (factor < 1)
            throw Lept.Arg(func, "sampling factor < 1");

        if (fract == 0.0)
            return Copy(pixd, pixs);

        /* If there is a colormap, remove it. */
        Pix pixt;
        if (cmap != null)
            pixt = pixs.RemoveColormap(REMOVE_CMAP_BASED_ON_SRC);
        else
            pixt = Clone(pixs);

        /* Make a copy if necessary */
        pixd = Copy(pixd, pixt);

        d = pixd.Depth;
        if (d == 8) {
            Numa na = Numa.EqualizeTRC(pixd, fract, factor);
            pixd.TRCMap(null, na);
        } else {  /* 32 bpp */
            Pix pix8 = pixd.GetRGBComponent(COLOR_RED);
            Numa na = Numa.EqualizeTRC(pix8, fract, factor);
            pix8.TRCMap(null, na);
            pixd.SetRGBComponent(pix8, COLOR_RED);
            pix8 = pixd.GetRGBComponent(COLOR_GREEN);
            na = Numa.EqualizeTRC(pix8, fract, factor);
            pix8.TRCMap(null, na);
            pixd.SetRGBComponent(pix8, COLOR_GREEN);
            pix8 = pixd.GetRGBComponent(COLOR_BLUE);
            na = Numa.EqualizeTRC(pix8, fract, factor);
            pix8.TRCMap(null, na);
            pixd.SetRGBComponent(pix8, COLOR_BLUE);
        }

        return pixd;
    }

    /*-------------------------------------------------------------*
     *                       Generic TRC mapping                   *
     *-------------------------------------------------------------*/
    // leptonica: pixTRCMap (enhance.c)
    /// <summary>In-place TRC mapping of a 8 bpp gray or 32 bpp rgb image.</summary>
    /// <param name="pixm">[optional] 1 bpp mask</param>
    /// <param name="na">mapping array</param>
    /// <remarks>
    /// (1) This operation is in-place on pixs.
    /// (2) For 32 bpp, this applies the same map to each of the r,g,b
    ///     components.
    /// (3) The mapping array is of size 256, and it maps the input
    ///     index into values in the range [0, 255].
    /// (4) If defined, the optional 1 bpp mask pixm has its origin
    ///     aligned with pixs, and the map function is applied only
    ///     to pixels in pixs under the fg of pixm.
    /// (5) For 32 bpp, this does not save the alpha channel.
    /// </remarks>
    public void TRCMap(Pix? pixm, Numa na)
    {
        const string func = "pixTRCMap";

        if (Colormap != null)
            throw Lept.Arg(func, "pixs is colormapped");
        if (na.Count != 256)
            throw Lept.Arg(func, "na not of size 256");
        GetDimensions(out int w, out int h, out int d);
        if (d != 8 && d != 32)
            throw Lept.Arg(func, "pixs not 8 or 32 bpp");
        if (pixm != null) {
            if (pixm.Depth != 1)
                throw Lept.Arg(func, "pixm not 1 bpp");
        }

        uint[] tab = ToUIntArray(na.GetIArray());  /* get the array for efficiency */
        int wpl = Wpl;
        uint[] data = Data;
        if (pixm == null) {
            if (d == 8) {
                ref uint tabRef = ref MemoryMarshal.GetArrayDataReference(tab);
                int fullwords = w >> 2;
                for (int i = 0; i < h; i++) {
                    ref uint lineRef = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(data), (nuint)(i * wpl));
                    for (int jw = 0; jw < fullwords; jw++) {
                        uint sw = Unsafe.Add(ref lineRef, (nuint)jw);
                        uint b0 = Unsafe.Add(ref tabRef, (nuint)(sw >> 24));
                        uint b1 = Unsafe.Add(ref tabRef, (nuint)((sw >> 16) & 0xff));
                        uint b2 = Unsafe.Add(ref tabRef, (nuint)((sw >> 8) & 0xff));
                        uint b3 = Unsafe.Add(ref tabRef, (nuint)(sw & 0xff));
                        Unsafe.Add(ref lineRef, (nuint)jw) = (b0 << 24) | (b1 << 16) | (b2 << 8) | b3;
                    }
                    for (int j = fullwords << 2; j < w; j++) {
                        int sval8 = GetDataByteUnchecked(ref lineRef, j);
                        SetDataByteUnchecked(ref lineRef, j, (int)Unsafe.Add(ref tabRef, (nuint)sval8));
                    }
                }
            } else {  /* d == 32 */
                ref uint tabRef = ref MemoryMarshal.GetArrayDataReference(tab);
                for (int i = 0; i < h; i++) {
                    ref uint lineRef = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(data), (nuint)(i * wpl));
                    for (int j = 0; j < w; j++) {
                        uint sval32 = Unsafe.Add(ref lineRef, (nuint)j);
                        Unsafe.Add(ref lineRef, (nuint)j) =
                            (Unsafe.Add(ref tabRef, (nuint)((sval32 >> L_RED_SHIFT) & 0xff)) << L_RED_SHIFT) |
                            (Unsafe.Add(ref tabRef, (nuint)((sval32 >> L_GREEN_SHIFT) & 0xff)) << L_GREEN_SHIFT) |
                            (Unsafe.Add(ref tabRef, (nuint)((sval32 >> L_BLUE_SHIFT) & 0xff)) << L_BLUE_SHIFT);
                    }
                }
            }
        } else {
            uint[] datam = pixm.Data;
            int wplm = pixm.Wpl;
            pixm.GetDimensions(out int wm, out int hm, out _);
            if (d == 8) {
                for (int i = 0; i < h; i++) {
                    if (i >= hm)
                        break;
                    Span<uint> line = data.AsSpan(i * wpl, wpl);
                    Span<uint> linem = datam.AsSpan(i * wplm, wplm);
                    for (int j = 0; j < w; j++) {
                        if (j >= wm)
                            break;
                        if (GetDataBit(linem, j) == 0)
                            continue;
                        int sval8 = GetDataByte(line, j);
                        int dval8 = (int)tab[sval8];
                        SetDataByte(line, j, dval8);
                    }
                }
            } else {  /* d == 32 */
                for (int i = 0; i < h; i++) {
                    if (i >= hm)
                        break;
                    int line = i * wpl;
                    Span<uint> linem = datam.AsSpan(i * wplm, wplm);
                    for (int j = 0; j < w; j++) {
                        if (j >= wm)
                            break;
                        if (GetDataBit(linem, j) == 0)
                            continue;
                        uint sval32 = data[line + j];
                        uint dval32 =
                            tab[(sval32 >> L_RED_SHIFT) & 0xff] << L_RED_SHIFT |
                            tab[(sval32 >> L_GREEN_SHIFT) & 0xff] << L_GREEN_SHIFT |
                            tab[(sval32 >> L_BLUE_SHIFT) & 0xff] << L_BLUE_SHIFT;
                        data[line + j] = dval32;
                    }
                }
            }
        }
    }

    private static uint[] ToUIntArray(int[] iarray)
    {
        uint[] tab = new uint[iarray.Length];
        for (int i = 0; i < iarray.Length; i++)
            tab[i] = (uint)iarray[i];
        return tab;
    }

    // leptonica: pixTRCMapGeneral (enhance.c)
    /// <summary>In-place TRC mapping of a 32 bpp rgb image with a separate map per channel.</summary>
    /// <param name="pixm">[optional] 1 bpp mask</param>
    /// <param name="nar">red mapping array</param>
    /// <param name="nag">green mapping array</param>
    /// <param name="nab">blue mapping array</param>
    /// <remarks>
    /// (1) This operation is in-place on %pixs.
    /// (2) Each of the r,g,b mapping arrays is of size 256. They map the
    ///     input value for that color component into values in the
    ///     range [0, 255].
    /// (3) In the special case where the r, g and b mapping arrays are
    ///     all the same, call pixTRCMap() instead.
    /// (4) If defined, the optional 1 bpp mask %pixm has its origin
    ///     aligned with %pixs, and the map function is applied only
    ///     to pixels in %pixs under the fg of pixm.
    /// (5) The alpha channel is not saved.
    /// </remarks>
    public void TRCMapGeneral(Pix? pixm, Numa nar, Numa nag, Numa nab)
    {
        const string func = "pixTRCMapGeneral";

        if (Depth != 32)
            throw Lept.Arg(func, "pixs not defined or not 32 bpp");
        if (pixm != null && pixm.Depth != 1)
            throw Lept.Arg(func, "pixm defined and not 1 bpp");
        if (nar.Count != 256 || nag.Count != 256 || nab.Count != 256)
            throw Lept.Arg(func, "na{r,g,b} not all of size 256");

        /* Get the arrays for efficiency */
        uint[] tabr = ToUIntArray(nar.GetIArray());
        uint[] tabg = ToUIntArray(nag.GetIArray());
        uint[] tabb = ToUIntArray(nab.GetIArray());
        GetDimensions(out int w, out int h, out _);
        int wpl = Wpl;
        uint[] data = Data;
        if (pixm == null) {
            for (int i = 0; i < h; i++) {
                int line = i * wpl;
                for (int j = 0; j < w; j++) {
                    uint sval32 = data[line + j];
                    uint dval32 =
                        tabr[(sval32 >> L_RED_SHIFT) & 0xff] << L_RED_SHIFT |
                        tabg[(sval32 >> L_GREEN_SHIFT) & 0xff] << L_GREEN_SHIFT |
                        tabb[(sval32 >> L_BLUE_SHIFT) & 0xff] << L_BLUE_SHIFT;
                    data[line + j] = dval32;
                }
            }
        } else {
            uint[] datam = pixm.Data;
            int wplm = pixm.Wpl;
            pixm.GetDimensions(out int wm, out int hm, out _);
            for (int i = 0; i < h; i++) {
                if (i >= hm)
                    break;
                int line = i * wpl;
                Span<uint> linem = datam.AsSpan(i * wplm, wplm);
                for (int j = 0; j < w; j++) {
                    if (j >= wm)
                        break;
                    if (GetDataBit(linem, j) == 0)
                        continue;
                    uint sval32 = data[line + j];
                    uint dval32 =
                        tabr[(sval32 >> L_RED_SHIFT) & 0xff] << L_RED_SHIFT |
                        tabg[(sval32 >> L_GREEN_SHIFT) & 0xff] << L_GREEN_SHIFT |
                        tabb[(sval32 >> L_BLUE_SHIFT) & 0xff] << L_BLUE_SHIFT;
                    data[line + j] = dval32;
                }
            }
        }
    }

