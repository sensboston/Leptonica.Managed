    // leptonica: pixUnsharpMaskingGray (enhance.c)
    /// <summary>Sharpens an 8 bpp image by unsharp masking.</summary>
    /// <param name="halfwidth">"half-width" of smoothing filter</param>
    /// <param name="fract">fraction of edge added back into image</param>
    /// <returns>pixd; a clone of this if no sharpening is requested</returns>
    /// <remarks>
    /// (1) We use symmetric smoothing filters of odd dimension,
    ///     typically use sizes of 3, 5, 7, etc.  The %halfwidth parameter
    ///     for these is (size - 1)/2; i.e., 1, 2, 3, etc.
    /// (2) The fract parameter is typically taken in the range:
    ///     0.2 &lt; fract &lt; 0.7
    /// (3) Returns a clone if no sharpening is requested.
    /// </remarks>
    public Pix UnsharpMaskingGray(int halfwidth, float fract)
    {
        const string func = "pixUnsharpMaskingGray";

        GetDimensions(out int w, out int h, out int d);
        if (d != 8 || Colormap != null)
            throw Lept.Arg(func, "pixs not 8 bpp or has cmap");
        if (fract <= 0.0 || halfwidth <= 0) {
            Log.Warning(func, "no sharpening requested; clone returned");
            return Clone(this);
        }
        if (halfwidth == 1 || halfwidth == 2)
            return UnsharpMaskingGrayFast(halfwidth, fract, L_BOTH_DIRECTIONS);

        Pix pixc = BlockconvGray(null, halfwidth, halfwidth);

        Pix pixd = CreateTemplateNoInit(this);
        uint[] datas = Data;
        uint[] datac = pixc.Data;
        uint[] datad = pixd.Data;
        int wpl = Wpl;
        int fullwords = w >> 2;
        LeptParallel.ForRows(h, (long)w * 6L, (yStart, yEnd) => {
            ref uint baseS = ref MemoryMarshal.GetArrayDataReference(datas);
            ref uint baseC = ref MemoryMarshal.GetArrayDataReference(datac);
            ref uint baseD = ref MemoryMarshal.GetArrayDataReference(datad);
            for (int i = yStart; i < yEnd; i++) {
                ref uint rs = ref Unsafe.Add(ref baseS, (nuint)(i * wpl));
                ref uint rc = ref Unsafe.Add(ref baseC, (nuint)(i * wpl));
                ref uint rd = ref Unsafe.Add(ref baseD, (nuint)(i * wpl));
                for (int jw = 0; jw < fullwords; jw++) {
                    uint sw = Unsafe.Add(ref rs, (nuint)jw);
                    uint cw = Unsafe.Add(ref rc, (nuint)jw);
                    int s0 = (int)(sw >> 24), c0 = (int)(cw >> 24);
                    int s1 = (int)((sw >> 16) & 0xff), c1 = (int)((cw >> 16) & 0xff);
                    int s2 = (int)((sw >> 8) & 0xff), c2 = (int)((cw >> 8) & 0xff);
                    int s3 = (int)(sw & 0xff), c3 = (int)(cw & 0xff);
                    uint v0 = (uint)Math.Clamp((int)((s0 - c0) * fract) + s0, 0, 255);
                    uint v1 = (uint)Math.Clamp((int)((s1 - c1) * fract) + s1, 0, 255);
                    uint v2 = (uint)Math.Clamp((int)((s2 - c2) * fract) + s2, 0, 255);
                    uint v3 = (uint)Math.Clamp((int)((s3 - c3) * fract) + s3, 0, 255);
                    Unsafe.Add(ref rd, (nuint)jw) = (v0 << 24) | (v1 << 16) | (v2 << 8) | v3;
                }
                for (int j = fullwords << 2; j < w; j++) {
                    int s = GetDataByteUnchecked(ref rs, j);
                    int c = GetDataByteUnchecked(ref rc, j);
                    SetDataByteUnchecked(ref rd, j, Math.Clamp((int)((s - c) * fract) + s, 0, 255));
                }
            }
        });

        return pixd;
    }

    // leptonica: pixUnsharpMaskingFast (enhance.c)
    /// <summary>Sharpens by unsharp masking with separable 1-D filters of half-width 1 or 2.</summary>
    /// <param name="halfwidth">"half-width" of smoothing filter; 1 and 2 only</param>
    /// <param name="fract">fraction of high frequency added to image</param>
    /// <param name="direction">L_HORIZ, L_VERT, L_BOTH_DIRECTIONS</param>
    /// <returns>pixd; a clone of this if no sharpening is requested</returns>
    /// <remarks>
    /// (1) The fast version uses separable 1-D filters directly on
    ///     the input image.  The halfwidth is either 1 (full width = 3)
    ///     or 2 (full width = 5).
    /// (2) The fract parameter is typically taken in the
    ///       range:  0.2 &lt; fract &lt; 0.7
    /// (3) To skip horizontal sharpening, use %fracth = 0.0; ditto for %fractv
    /// (4) For one dimensional filtering (as an example):
    ///     For %halfwidth = 1, the low-pass filter is
    ///         L:    1/3    1/3   1/3
    ///     and the high-pass filter is
    ///         H = I - L:   -1/3   2/3   -1/3
    ///     For %halfwidth = 2, the low-pass filter is
    ///         L:    1/5    1/5   1/5    1/5    1/5
    ///     and the high-pass filter is
    ///         H = I - L:   -1/5  -1/5   4/5  -1/5   -1/5
    ///     The new sharpened pixel value is found by adding some fraction
    ///     of the high-pass filter value (which sums to 0) to the
    ///     initial pixel value:
    ///         N = I + fract * H
    /// (5) For 2D, the sharpening filter is not separable, because the
    ///     vertical filter depends on the horizontal location relative
    ///     to the filter origin, and v.v.   So we either do the full
    ///     2D filter (for %halfwidth == 1) or do the low-pass
    ///     convolution separably and then compose with the original pix.
    /// (6) Returns a clone if no sharpening is requested.
    /// </remarks>
    public Pix UnsharpMaskingFast(int halfwidth, float fract, int direction)
    {
        const string func = "pixUnsharpMaskingFast";

        if (Depth == 1)
            throw Lept.Arg(func, "pixs not defined or 1 bpp");
        if (fract <= 0.0 || halfwidth <= 0) {
            Log.Warning(func, "no sharpening requested; clone returned");
            return Clone(this);
        }
        if (halfwidth != 1 && halfwidth != 2)
            throw Lept.Arg(func, "halfwidth must be 1 or 2");
        if (direction != L_HORIZ && direction != L_VERT &&
            direction != L_BOTH_DIRECTIONS)
            throw Lept.Arg(func, "invalid direction");

        /* Remove colormap; clone if possible; result is either 8 or 32 bpp */
        Pix pixt = ConvertTo8Or32(L_CLONE, 0);

        /* Sharpen */
        Pix pixd;
        int d = pixt.Depth;
        if (d == 8) {
            pixd = pixt.UnsharpMaskingGrayFast(halfwidth, fract, direction);
        } else {  /* d == 32 */
            // NOTE(upstream): the components are taken from pixs, not from pixt
            Pix pixr = GetRGBComponent(COLOR_RED);
            Pix pixrs = pixr.UnsharpMaskingGrayFast(halfwidth, fract, direction);
            Pix pixg = GetRGBComponent(COLOR_GREEN);
            Pix pixgs = pixg.UnsharpMaskingGrayFast(halfwidth, fract, direction);
            Pix pixb = GetRGBComponent(COLOR_BLUE);
            Pix pixbs = pixb.UnsharpMaskingGrayFast(halfwidth, fract, direction);
            pixd = CreateRGBImage(pixrs, pixgs, pixbs);
            if (Spp == 4)
                pixd.CopyRGBComponent(this, L_ALPHA_CHANNEL);
        }

        return pixd;
    }

