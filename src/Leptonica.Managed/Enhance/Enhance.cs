    /// <summary>Measures the average saturation of a 32 bpp rgb image.</summary>
    /// <param name="factor">subsampling factor; integer &gt;= 1</param>
    /// <returns>average saturation</returns>
    public float MeasureSaturation(int factor)
    {
        const string func = "pixMeasureSaturation";

        GetDimensions(out int w, out int h, out int d);
        if (d != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
        if (factor < 1)
            throw Lept.Arg(func, "subsampling factor < 1");

        uint[] data = Data;
        int wpl = Wpl;
        int sum = 0, count = 0;
        for (int i = 0; i < h; i += factor) {
            int line = i * wpl;
            for (int j = 0; j < w; j += factor) {
                ExtractRGBValues(data[line + j], out int rval, out int gval, out int bval);
                ConvertRGBToHSV(rval, gval, bval, out _, out int sval, out _);
                sum += sval;
                count++;
            }
        }

        float sat = 0.0f;
        if (count > 0)
            sat = (float)sum / (float)count;
        return sat;
    }

