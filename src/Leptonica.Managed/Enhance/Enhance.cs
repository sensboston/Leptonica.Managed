    /// </remarks>
    public static Pix GammaTRCWithAlpha(Pix? pixd, Pix pixs, float gamma, int minval, int maxval)
    {
        const string func = "pixGammaTRCWithAlpha";

        if (pixs.Depth != 32)
            throw Lept.Arg(func, "pixs undefined or not 32 bpp");
        if (pixd != null && pixd != pixs)
            throw Lept.Arg(func, "pixd not null or pixs");
        if (gamma <= 0.0) {
            Log.Warning(func, "gamma must be > 0.0; setting to 1.0");
            gamma = 1.0f;
        }
        if (minval >= maxval)
            throw Lept.Arg(func, "minval not < maxval");

        if (gamma == 1.0 && minval == 0 && maxval == 255)
            return Copy(pixd, pixs);
        if (pixd == null)  /* start with a copy if not in-place */
            pixd = Copy(null, pixs);

        Pix pixalpha = pixs.GetRGBComponent(L_ALPHA_CHANNEL);  /* save */
