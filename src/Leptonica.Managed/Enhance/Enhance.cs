    // leptonica: pixUnsharpMaskingGray1D (enhance.c)
    /// <summary>Sharpens an 8 bpp image in one direction with a filter of half-width 1 or 2.</summary>
    /// <param name="halfwidth">"half-width" of smoothing filter: 1 or 2</param>
    /// <param name="fract">fraction of high frequency added to image</param>
    /// <param name="direction">filtering direction; use L_HORIZ or L_VERT</param>
    /// <returns>pixd; a clone of this if no sharpening is requested</returns>
    /// <remarks>
    /// (1) For usage and explanation of the algorithm, see notes
    ///     in pixUnsharpMaskingFast().
    /// (2) Returns a clone if no sharpening is requested.
    /// </remarks>
    public Pix UnsharpMaskingGray1D(int halfwidth, float fract, int direction)
    {
        const string func = "pixUnsharpMaskingGray1D";

        GetDimensions(out int w, out int h, out int d);
        if (d != 8 || Colormap != null)
            throw Lept.Arg(func, "pixs not 8 bpp or has cmap");
        if (fract <= 0.0 || halfwidth <= 0) {
            Log.Warning(func, "no sharpening requested; clone returned");
            return Clone(this);
        }
        if (halfwidth != 1 && halfwidth != 2)
            throw Lept.Arg(func, "halfwidth must be 1 or 2");

        /* Initialize pixd with pixels from pixs that will not be
         * set when computing the sharpened values. */
        Pix pixd = CopyBorder(null, this, halfwidth, halfwidth, halfwidth, halfwidth);
        uint[] datas = Data;
        uint[] datad = pixd.Data;
        int wpls = Wpl;
        int wpld = pixd.Wpl;

        float[] a = new float[5];
        if (halfwidth == 1) {
            a[0] = (float)(-fract / 3.0);
            a[1] = (float)(1.0 + fract * 2.0 / 3.0);
            a[2] = a[0];
        } else {  /* halfwidth == 2 */
            a[0] = (float)(-fract / 5.0);
            a[1] = a[0];
            a[2] = (float)(1.0 + fract * 4.0 / 5.0);
            a[3] = a[0];
            a[4] = a[0];
        }

        float val;
        int ival;
        if (direction == L_HORIZ) {
            for (int i = 0; i < h; i++) {
                Span<uint> lines = datas.AsSpan(i * wpls, wpls);
                Span<uint> lined = datad.AsSpan(i * wpld, wpld);
                if (halfwidth == 1) {
                    for (int j = 1; j < w - 1; j++) {
                        val = a[0] * GetDataByte(lines, j - 1) +
                              a[1] * GetDataByte(lines, j) +
                              a[2] * GetDataByte(lines, j + 1);
                        ival = (int)val;
                        ival = Math.Max(0, ival);
                        ival = Math.Min(255, ival);
                        SetDataByte(lined, j, ival);
                    }
                } else {  /* halfwidth == 2 */
                    for (int j = 2; j < w - 2; j++) {
                        val = a[0] * GetDataByte(lines, j - 2) +
                              a[1] * GetDataByte(lines, j - 1) +
                              a[2] * GetDataByte(lines, j) +
                              a[3] * GetDataByte(lines, j + 1) +
                              a[4] * GetDataByte(lines, j + 2);
                        ival = (int)val;
                        ival = Math.Max(0, ival);
                        ival = Math.Min(255, ival);
                        SetDataByte(lined, j, ival);
                    }
                }
            }
        } else {  /* direction == L_VERT */
            if (halfwidth == 1) {
                for (int i = 1; i < h - 1; i++) {
                    Span<uint> lines0 = datas.AsSpan((i - 1) * wpls, wpls);
                    Span<uint> lines1 = datas.AsSpan(i * wpls, wpls);
                    Span<uint> lines2 = datas.AsSpan((i + 1) * wpls, wpls);
                    Span<uint> lined = datad.AsSpan(i * wpld, wpld);
                    for (int j = 0; j < w; j++) {
                        val = a[0] * GetDataByte(lines0, j) +
                              a[1] * GetDataByte(lines1, j) +
                              a[2] * GetDataByte(lines2, j);
                        ival = (int)val;
                        ival = Math.Max(0, ival);
                        ival = Math.Min(255, ival);
                        SetDataByte(lined, j, ival);
                    }
                }
            } else {  /* halfwidth == 2 */
                for (int i = 2; i < h - 2; i++) {
                    Span<uint> lines0 = datas.AsSpan((i - 2) * wpls, wpls);
                    Span<uint> lines1 = datas.AsSpan((i - 1) * wpls, wpls);
                    Span<uint> lines2 = datas.AsSpan(i * wpls, wpls);
                    Span<uint> lines3 = datas.AsSpan((i + 1) * wpls, wpls);
                    Span<uint> lines4 = datas.AsSpan((i + 2) * wpls, wpls);
                    Span<uint> lined = datad.AsSpan(i * wpld, wpld);
                    for (int j = 0; j < w; j++) {
                        val = a[0] * GetDataByte(lines0, j) +
                              a[1] * GetDataByte(lines1, j) +
                              a[2] * GetDataByte(lines2, j) +
                              a[3] * GetDataByte(lines3, j) +
                              a[4] * GetDataByte(lines4, j);
                        ival = (int)val;
                        ival = Math.Max(0, ival);
                        ival = Math.Min(255, ival);
                        SetDataByte(lined, j, ival);
                    }
                }
            }
        }

        return pixd;
    }

    // leptonica: pixUnsharpMaskingGray2D (enhance.c)
    /// <summary>Sharpens an 8 bpp image in both directions with a separable low-pass filter of half-width 1 or 2.</summary>
    /// <param name="halfwidth">"half-width" of smoothing filter: 1 or 2</param>
    /// <param name="fract">fraction of high frequency added to image</param>
    /// <returns>pixd; a clone of this if no sharpening is requested</returns>
    /// <remarks>
    /// (1) This is for %halfwidth == 1, 2.
    /// (2) The lowpass filter is implemented separably.
    /// (3) Returns a clone if no sharpening is requested.
    /// </remarks>
    public Pix UnsharpMaskingGray2D(int halfwidth, float fract)
    {
        const string func = "pixUnsharpMaskingGray2D";

        GetDimensions(out int w, out int h, out int d);
        if (d != 8 || Colormap != null)
            throw Lept.Arg(func, "pixs not 8 bpp or has cmap");
        if (fract <= 0.0 || halfwidth <= 0) {
            Log.Warning(func, "no sharpening requested; clone returned");
            return Clone(this);
        }
        if (halfwidth != 1 && halfwidth != 2)
            throw Lept.Arg(func, "halfwidth must be 1 or 2");

        Pix pixd = CopyBorder(null, this, halfwidth, halfwidth, halfwidth, halfwidth);
        uint[] datad = pixd.Data;
        int wpld = pixd.Wpl;
        uint[] datas = Data;
        int wpls = Wpl;

        if (halfwidth == 1) {
            UnsharpMaskingGray2DHw1(pixd, fract);
            return pixd;
        }

        /* Do the low pass separably using a pooled horizontal sum buffer. */
        using TempBuffer<float> hbuf = new TempBuffer<float>(w * h);
        float[] dataf = hbuf.Array;
        int wplf = w;
        if (halfwidth == 1) {
            for (int i = 0; i < h; i++) {
                ref uint rs = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(datas), (nuint)(i * wpls));
                ref float rf = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(dataf), (nuint)(i * wplf));
                for (int j = 1; j < w - 1; j++) {
                    Unsafe.Add(ref rf, (nuint)j) =
                        GetDataByteUnchecked(ref rs, j - 1) +
                        GetDataByteUnchecked(ref rs, j) +
                        GetDataByteUnchecked(ref rs, j + 1);
                }
            }
        } else {
            for (int i = 0; i < h; i++) {
                ref uint rs = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(datas), (nuint)(i * wpls));
                ref float rf = ref Unsafe.Add(ref MemoryMarshal.GetArrayDataReference(dataf), (nuint)(i * wplf));
                for (int j = 2; j < w - 2; j++) {
                    Unsafe.Add(ref rf, (nuint)j) =
                        GetDataByteUnchecked(ref rs, j - 2) +
                        GetDataByteUnchecked(ref rs, j - 1) +
                        GetDataByteUnchecked(ref rs, j) +
                        GetDataByteUnchecked(ref rs, j + 1) +
                        GetDataByteUnchecked(ref rs, j + 2);
                }
            }
        }

        if (halfwidth == 1) {
            const float norm1 = 1.0f / 9.0f;
            LeptParallel.ForRows(Math.Max(0, h - 2), (long)w * 8L, (rStart, rEnd) => {
                ref float baseF = ref MemoryMarshal.GetArrayDataReference(dataf);
                ref uint baseS = ref MemoryMarshal.GetArrayDataReference(datas);
                ref uint baseD = ref MemoryMarshal.GetArrayDataReference(datad);
                for (int r = rStart; r < rEnd; r++) {
                    int i = r + 1;
                    ref float rf0 = ref Unsafe.Add(ref baseF, (nuint)((i - 1) * wplf));
                    ref float rf1 = ref Unsafe.Add(ref baseF, (nuint)(i * wplf));
                    ref float rf2 = ref Unsafe.Add(ref baseF, (nuint)((i + 1) * wplf));
                    ref uint rs = ref Unsafe.Add(ref baseS, (nuint)(i * wpls));
                    ref uint rd = ref Unsafe.Add(ref baseD, (nuint)(i * wpld));
                    for (int j = 1; j < w - 1; j++) {
                        float low = norm1 * (Unsafe.Add(ref rf0, (nuint)j) + Unsafe.Add(ref rf1, (nuint)j) + Unsafe.Add(ref rf2, (nuint)j));
                        int sval = GetDataByteUnchecked(ref rs, j);
                        int ival = Math.Clamp((int)(sval + fract * (sval - low) + 0.5), 0, 255);
                        SetDataByteUnchecked(ref rd, j, ival);
                    }
                }
            });
        } else {
            const float norm2 = 1.0f / 25.0f;
            LeptParallel.ForRows(Math.Max(0, h - 4), (long)w * 10L, (rStart, rEnd) => {
                ref float baseF = ref MemoryMarshal.GetArrayDataReference(dataf);
                ref uint baseS = ref MemoryMarshal.GetArrayDataReference(datas);
                ref uint baseD = ref MemoryMarshal.GetArrayDataReference(datad);
                for (int r = rStart; r < rEnd; r++) {
                    int i = r + 2;
                    ref float rf0 = ref Unsafe.Add(ref baseF, (nuint)((i - 2) * wplf));
                    ref float rf1 = ref Unsafe.Add(ref baseF, (nuint)((i - 1) * wplf));
                    ref float rf2 = ref Unsafe.Add(ref baseF, (nuint)(i * wplf));
                    ref float rf3 = ref Unsafe.Add(ref baseF, (nuint)((i + 1) * wplf));
                    ref float rf4 = ref Unsafe.Add(ref baseF, (nuint)((i + 2) * wplf));
                    ref uint rs = ref Unsafe.Add(ref baseS, (nuint)(i * wpls));
                    ref uint rd = ref Unsafe.Add(ref baseD, (nuint)(i * wpld));
                    for (int j = 2; j < w - 2; j++) {
                        float low = norm2 * (Unsafe.Add(ref rf0, (nuint)j) + Unsafe.Add(ref rf1, (nuint)j) +
                                             Unsafe.Add(ref rf2, (nuint)j) + Unsafe.Add(ref rf3, (nuint)j) +
                                             Unsafe.Add(ref rf4, (nuint)j));
                        int sval = GetDataByteUnchecked(ref rs, j);
                        int ival = Math.Clamp((int)(sval + fract * (sval - low) + 0.5), 0, 255);
                        SetDataByteUnchecked(ref rd, j, ival);
                    }
                }
            });
        }

        return pixd;
    }

    /// <summary>
    /// 2D unsharp masking of this 8 bpp image with halfwidth 1; writes the interior
    /// pixels (all but the outer ring) of pixd.
    /// </summary>
    /// <remarks>
    /// The 3x3 sums are exact integers, so they are formed with integer adds; the
    /// floating point steps are the same as in the scalar expression
    /// ival = (int)(sval + fract * (sval - low) + 0.5).
    /// </remarks>
    internal void UnsharpMaskingGray2DHw1(Pix pixd, float fract)
    {
        int w = Width;
        int h = Height;
        if (w < 3 || h < 3)
            return;

        uint[] datas = Data;
        uint[] datad = pixd.Data;
        int wpls = Wpl;
        int wpld = pixd.Wpl;
        const float norm1 = 1.0f / 9.0f;
        bool simd = RgbSimd.IsSupported && fract <= 1000.0f;   // false for NaN
        int stride = ((wpls * 4 + 15) & ~15) + 16;

        LeptParallel.ForRows(h - 2, (long)w * 8L, (rStart, rEnd) => {
            using TempBuffer<byte> rowbuf = new TempBuffer<byte>(3 * stride);
            using TempBuffer<int> vsbuf = new TempBuffer<int>(stride);
            byte[] rows = rowbuf.Array;
            int[] vs = vsbuf.Array;
            int o0 = 0, o1 = stride, o2 = 2 * stride;
            RgbSimd.ToPixelOrder(datas, rStart * wpls, wpls, rows, o0);
            RgbSimd.ToPixelOrder(datas, (rStart + 1) * wpls, wpls, rows, o1);

            int kmax = simd ? (w - 5) / 4 : 0;   // last dest word that lies fully inside [1, w-2]
            if (w < 5)
                kmax = 0;
            Vector128<float> fractv = Vector128.Create(fract);
            Vector128<float> normv = Vector128.Create(norm1);
            Vector128<float> halfv = Vector128.Create(0.5f);
            Vector128<int> zerov = Vector128<int>.Zero;
            Vector128<int> maxv = Vector128.Create(255);

            for (int r = rStart; r < rEnd; r++) {
                int i = r + 1;
                RgbSimd.ToPixelOrder(datas, (i + 1) * wpls, wpls, rows, o2);

                    /* Vertical sums of 3 rows, as ints */
                for (int k = 0; k < wpls * 4; k += 16) {
                    Vector128<byte> a = Vector128.LoadUnsafe(ref rows[o0 + k]);
                    Vector128<byte> b = Vector128.LoadUnsafe(ref rows[o1 + k]);
                    Vector128<byte> c = Vector128.LoadUnsafe(ref rows[o2 + k]);
                    Vector128<ushort> lo = Vector128.WidenLower(a) + Vector128.WidenLower(b) + Vector128.WidenLower(c);
                    Vector128<ushort> hi = Vector128.WidenUpper(a) + Vector128.WidenUpper(b) + Vector128.WidenUpper(c);
                    Vector128.WidenLower(lo).AsInt32().StoreUnsafe(ref vs[k]);
                    Vector128.WidenUpper(lo).AsInt32().StoreUnsafe(ref vs[k + 4]);
                    Vector128.WidenLower(hi).AsInt32().StoreUnsafe(ref vs[k + 8]);
                    Vector128.WidenUpper(hi).AsInt32().StoreUnsafe(ref vs[k + 12]);
                }

                ref uint rd = ref datad[i * wpld];
                int jEnd = w - 2;                     // last interior column
                int jv0 = kmax >= 1 ? 4 : jEnd + 1;   // first column of the vector part
                int jv1 = kmax >= 1 ? 4 * (kmax + 1) : jEnd + 1;   // end of the vector part

                for (int j = 1; j < jv0 && j <= jEnd; j++)
                    SharpenPixel(ref rd, j, vs, rows[o1 + j], fract);

                ref int rvs = ref vs[0];
                ref byte rcen = ref rows[o1];
                for (int j = jv0; j < jv1; j += 4) {
                    Vector128<int> s9 = Vector128.LoadUnsafe(ref rvs, (nuint)(j - 1))
                                      + Vector128.LoadUnsafe(ref rvs, (nuint)j)
                                      + Vector128.LoadUnsafe(ref rvs, (nuint)(j + 1));
                    Vector128<float> low = Vector128.ConvertToSingle(s9) * normv;
                    uint cw = Unsafe.ReadUnaligned<uint>(ref Unsafe.Add(ref rcen, j));
                    Vector128<int> sval = Vector128.WidenLower(Vector128.WidenLower(
                        Vector128.CreateScalarUnsafe(cw).AsByte())).AsInt32();
                    Vector128<float> sv = Vector128.ConvertToSingle(sval);
                    Vector128<float> g = sv + fractv * (sv - low);
                    Vector128<int> t = Vector128.ConvertToInt32(g);
                    Vector128<float> fr = g - Vector128.ConvertToSingle(t);
                    Vector128<int> res = t - Vector128.GreaterThanOrEqual(fr, halfv).AsInt32();
                    res = Vector128.Min(Vector128.Max(res, zerov), maxv);
                    Unsafe.Add(ref rd, j >> 2) = Vector128.Shuffle(res.AsByte(), s_packIdx).AsUInt32().ToScalar();
                }

                for (int j = jv1; j <= jEnd; j++)
                    SharpenPixel(ref rd, j, vs, rows[o1 + j], fract);

                int t0 = o0;
                o0 = o1;
                o1 = o2;
                o2 = t0;
            }
        });
    }

    // Picks byte 0 of every int lane (in reverse order) into the first word.
    private static readonly Vector128<byte> s_packIdx = Vector128.Create(
        (byte)12, 8, 4, 0, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80, 0x80);

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static void SharpenPixel(ref uint rd, int j, int[] vs, int sval, float fract)
    {
        const float norm1 = 1.0f / 9.0f;
        float low = norm1 * (float)(vs[j - 1] + vs[j] + vs[j + 1]);
        int ival = Math.Clamp((int)(sval + fract * (sval - low) + 0.5), 0, 255);
        SetDataByteUnchecked(ref rd, j, ival);
    }

