    // leptonica: numaGammaTRC (enhance.c)
    /// <summary>Makes a gamma tone reproduction curve table with 256 entries.</summary>
    /// <param name="gamma">gamma factor; must be &gt; 0.0</param>
    /// <param name="minval">input value that gives 0 for output</param>
    /// <param name="maxval">input value that gives 255 for output</param>
    /// <remarks>
    /// (1) The map is returned as a numa; values are clipped to [0, 255].
    /// (2) For a linear mapping, set gamma = 1.0.
    /// (3) To force all intensities into a range within fraction delta
    ///     of white, use: minval = -256 * (1 - delta) / delta
    ///                    maxval = 255
    /// (4) To force all intensities into a range within fraction delta
    ///     of black, use: minval = 0
    ///                    maxval = 256 * (1 - delta) / delta
    /// </remarks>
    public static Numa GammaTRC(float gamma, int minval, int maxval)
    {
        const string func = "numaGammaTRC";

        if (minval >= maxval)
            throw Lept.Arg(func, "minval not < maxval");
        if (gamma <= 0.0) {
            Log.Warning(func, "gamma must be > 0.0; setting to 1.0");
            gamma = 1.0f;
        }

        float invgamma = (float)(1.0 / gamma);
        Numa na = Create(256);
        for (int i = 0; i < minval; i++)
            na.AddNumber(0);
        for (int i = minval; i <= maxval; i++) {
            if (i < 0) continue;
            if (i > 255) continue;
            float x = (float)(i - minval) / (float)(maxval - minval);
            int val = (int)(255.0 * MathF.Pow(x, invgamma) + 0.5);
            val = Math.Max(val, 0);
            val = Math.Min(val, 255);
            na.AddNumber(val);
        }
        for (int i = maxval + 1; i < 256; i++)
            na.AddNumber(255);

        return na;
    }

    // leptonica: numaContrastTRC (enhance.c)
    /// <summary>Makes a contrast enhancement tone reproduction curve table with 256 entries.</summary>
    /// <param name="factor">generally between 0.0 [no enhancement]
    ///                      and 1.0, but can be larger than 1.0</param>
    /// <remarks>
    /// (1) The mapping is monotonic increasing, where 0 is mapped
    ///     to 0 and 255 is mapped to 255.
    /// (2) As 'factor' is increased from 0.0 (where the mapping is linear),
    ///     the map gets closer to its limit as a step function that
    ///     jumps from 0 to 255 at the center (input value = 127).
    /// </remarks>
    public static Numa ContrastTRC(float factor)
    {
        const string func = "numaContrastTRC";

        if (factor < 0.0) {
            Log.Warning(func, "factor must be >= 0.0; using 0.0; no enhancement");
            factor = 0.0f;
        }
        if (factor == 0.0)
            return MakeSequence(0, 1, 256);  /* linear map */

        double scale = Pix.EnhanceScaleFactor;
        double ymax = Math.Atan((double)(1.0 * factor * scale));
        double ymin = Math.Atan((double)(-127.0 * factor * scale / 128.0));
        double dely = ymax - ymin;
        Numa na = Create(256);
        for (int i = 0; i < 256; i++) {
            double x = (double)i;
            int val = (int)((255.0 / dely) *
                 (-ymin + Math.Atan((double)(factor * scale * (x - 127.0) / 128.0))) +
                     0.5);
            na.AddNumber(val);
        }

        return na;
    }

    // leptonica: numaEqualizeTRC (enhance.c)
    /// <summary>Makes a histogram equalization tone reproduction curve table with 256 entries.</summary>
    /// <param name="pix">8 bpp, no colormap</param>
    /// <param name="fract">fraction of equalization movement of pixel values</param>
    /// <param name="factor">subsampling factor; integer &gt;= 1</param>
    /// <remarks>
    /// (1) If fract == 0.0, no equalization will be performed.
    ///     If fract == 1.0, equalization is complete.
    /// (2) Set the subsampling factor &gt; 1 to reduce the amount of computation.
    /// (3) The map is returned as a numa with 256 values, specifying
    ///     the equalized value (array value) for every input value
    ///     (the array index).
    /// </remarks>
    public static Numa EqualizeTRC(Pix pix, float fract, int factor)
    {
        const string func = "numaEqualizeTRC";

        if (pix.Depth != 8)
            throw Lept.Arg(func, "pix not 8 bpp");
        if (fract < 0.0 || fract > 1.0)
            throw Lept.Arg(func, "fract not in [0.0 ... 1.0]");
        if (factor < 1)
            throw Lept.Arg(func, "sampling factor < 1");

        if (fract == 0.0)
            Log.Warning(func, "fract = 0.0; no equalization requested");

        Numa nah = pix.GetGrayHistogram(factor);
        float sum = nah.GetSum();
        Numa nasum = nah.GetPartialSums();

        Numa nad = Create(256);
        for (int iin = 0; iin < 256; iin++) {
            float val = nasum.GetFValue(iin);
            int itarg = (int)(255.0 * val / sum + 0.5);
            int iout = iin + (int)(fract * (itarg - iin));
            iout = Math.Min(iout, 255);  /* to be safe */
            nad.AddNumber(iout);
        }

        return nad;
    }
