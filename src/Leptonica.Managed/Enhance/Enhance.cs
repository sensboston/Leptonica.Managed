        if (halfwidth == 1 || halfwidth == 2)
            return UnsharpMaskingFast(halfwidth, fract, L_BOTH_DIRECTIONS);

        /* Remove colormap; clone if possible; result is either 8 or 32 bpp */
        Pix pix1 = ConvertTo8Or32(L_CLONE, 0);

