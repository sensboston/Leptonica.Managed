    /// <summary>Modifies the hue of a 32 bpp rgb image.</summary>
    /// <param name="pixd">[optional] can be null or equal to pixs</param>
    /// <param name="pixs">32 bpp rgb</param>
    /// <param name="fract">between -1.0 and 1.0</param>
    /// <remarks>
    /// (1) pixd must either be null or equal to pixs.
    ///     For in-place operation, set pixd == pixs:
    ///        pixEqualizeTRC(pixs, pixs, ...);
    ///     To get a new image, set pixd == null:
    ///        pixd = pixEqualizeTRC(NULL, pixs, ...);
    /// (2) Use fract &gt; 0.0 to increase hue value; &lt; 0.0 to decrease it.
    ///     1.0 (or -1.0) represents a 360 degree rotation; i.e., no change.
    /// (3) If no modification is requested (fract = -1.0 or 0 or 1.0),
    ///     return a copy unless in-place, in which case this is a no-op.
    /// (4) This leaves saturation and intensity invariant.
    /// (5) See discussion of color-modification methods, in coloring.c.
    /// </remarks>
    public static Pix ModifyHue(Pix? pixd, Pix pixs, float fract)
    {
        const string func = "pixModifyHue";

        if (pixs.Colormap != null)
            throw Lept.Arg(func, "pixs colormapped");
        if (pixd != null && pixd != pixs)
            throw Lept.Arg(func, "pixd not null or pixs");
        pixs.GetDimensions(out int w, out int h, out int d);
        if (d != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
        if (Math.Abs(fract) > 1.0)
            throw Lept.Arg(func, "fract not in [-1.0 ... 1.0]");

        pixd = Copy(pixd, pixs);

        int delhue = (int)(240 * fract);
        if (delhue == 0 || delhue == 240 || delhue == -240) {
            Log.Warning(func, "no change requested in hue");
            return pixd;
        }
        if (delhue < 0)
            delhue += 240;

        uint[] data = pixd.Data;
        int wpl = pixd.Wpl;
        for (int i = 0; i < h; i++) {
            int line = i * wpl;
            for (int j = 0; j < w; j++) {
                ExtractRGBValues(data[line + j], out int rval, out int gval, out int bval);
                ConvertRGBToHSV(rval, gval, bval, out int hval, out int sval, out int vval);
                hval = (hval + delhue) % 240;
                ConvertHSVToRGB(hval, sval, vval, out rval, out gval, out bval);
                ComposeRGBPixel(rval, gval, bval, out data[line + j]);
            }
        }
        if (pixs.Spp == 4)
            pixd.CopyRGBComponent(pixs, L_ALPHA_CHANNEL);

        return pixd;
    }

