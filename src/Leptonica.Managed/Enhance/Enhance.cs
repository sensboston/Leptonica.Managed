    // leptonica: pixMosaicColorShiftRGB (enhance.c)
    /// <summary>Generates a mosaic view of the effect of shifting the RGB components.</summary>
    /// <param name="roff">center offset of red component</param>
    /// <param name="goff">center offset of green component</param>
    /// <param name="boff">center offset of blue component</param>
    /// <param name="delta">increments from center offsets [0.0 - 0.1];
    ///                     use 0.0 to get the default (0.04)</param>
    /// <param name="nincr">number of increments in each (positive and negative)
    ///                     direction; use 0 to get the default (2).</param>
    /// <remarks>
    /// (1) This generates a mosaic view of the effect of shifting the RGB
    ///     components.  See pixColorShiftRGB() for details on the shifting.
    /// (2) The offsets (%roff, %goff, %boff) set the color center point,
    ///     and the deviations from this are shown separately for deltas
    ///     in r, g and b.  For each component, we show 2 * %nincr + 1
    ///     images.
    /// (3) The pix must have minimum dimensions of 100 and an aspect
    ///     ratio not exceeding 5.0.
    /// (4) Usage: color prints differ from the original due to three factors:
    ///     illumination, calibration of the camera in acquisition,
    ///     and calibration of the printer.  This function can be used
    ///     to iteratively match a color print to the original.  On each
    ///     iteration, the center offsets are set to the best match so
    ///     far, and the %delta increments are typically reduced.
    /// </remarks>
    public Pix MosaicColorShiftRGB(float roff, float goff, float boff, float delta, int nincr)
    {
        const string func = "pixMosaicColorShiftRGB";

        if (Depth != 32)
            throw Lept.Arg(func, "pixs undefined or not rgb");
        if (roff < -1.0 || roff > 1.0)
            throw Lept.Arg(func, "roff not in [-1.0, 1.0]");
        if (goff < -1.0 || goff > 1.0)
            throw Lept.Arg(func, "goff not in [-1.0, 1.0]");
        if (boff < -1.0 || boff > 1.0)
            throw Lept.Arg(func, "boff not in [-1.0, 1.0]");
        if (delta < 0.0 || delta > 0.1)
            throw Lept.Arg(func, "delta not in [0.0, 0.1]");
        if (delta == 0.0) delta = 0.04f;
        if (nincr < 0 || nincr > 6)
            throw Lept.Arg(func, "nincr not in [0, 6]");
        if (nincr == 0) nincr = 2;

        /* Require width and height to be >= 100, and the aspect ratio <= 5.0 */
        GetDimensions(out int w, out int h, out _);
        if (w < 100 || h < 100)
            throw Lept.Arg(func, "w and h not both >= 100");
        float ratio = MaxAspectRatio();
        if (ratio < 1.0 || ratio > 5.0)
            throw Lept.Arg(func, CFormat.Sprintf("invalid aspect ratio %5.1f", (double)ratio));

        Pixa pixa = Pixa.Create(3 * (2 * nincr + 1));
        L_Bmf bmf = L_Bmf.Create(null, 8);
        Pix pix1 = ScaleToSize(400, 0);
        float del;
        int i;
        for (i = 0, del = -nincr * delta; i < 2 * nincr + 1; i++, del += delta) {
            Pix pix2 = ColorShiftRGB(pix1, roff + del, goff, boff);
            string buf = CFormat.Sprintf("%4.2f, %4.2f, %4.2f",
                                         (double)(roff + del), (double)goff, (double)boff);
            Pix pix3 = pix2.AddSingleTextblock(bmf, buf, 0xff000000, L_ADD_BELOW, out _);
            pixa.AddPix(pix3, L_INSERT);
        }
        for (i = 0, del = -nincr * delta; i < 2 * nincr + 1; i++, del += delta) {
            Pix pix2 = ColorShiftRGB(pix1, roff, goff + del, boff);
            string buf = CFormat.Sprintf("%4.2f, %4.2f, %4.2f",
                                         (double)roff, (double)(goff + del), (double)boff);
            Pix pix3 = pix2.AddSingleTextblock(bmf, buf, 0xff000000, L_ADD_BELOW, out _);
            pixa.AddPix(pix3, L_INSERT);
        }
        for (i = 0, del = -nincr * delta; i < 2 * nincr + 1; i++, del += delta) {
            Pix pix2 = ColorShiftRGB(pix1, roff, goff, boff + del);
            string buf = CFormat.Sprintf("%4.2f, %4.2f, %4.2f",
                                         (double)roff, (double)goff, (double)(boff + del));
            Pix pix3 = pix2.AddSingleTextblock(bmf, buf, 0xff000000, L_ADD_BELOW, out _);
            pixa.AddPix(pix3, L_INSERT);
        }

        pix1 = pixa.DisplayTiledAndScaled(32, 300, 2 * nincr + 1, 0, 30, 2);
        return pix1;
    }

    // leptonica: pixColorShiftRGB (enhance.c)
    /// <summary>Shifts the r, g and b components independently by a fraction.</summary>
    /// <param name="pixs">32 bpp rgb</param>
    /// <param name="rfract">fractional shift in red component</param>
    /// <param name="gfract">fractional shift in green component</param>
    /// <param name="bfract">fractional shift in blue component</param>
    /// <remarks>
    /// (1) This allows independent fractional shifts of the r,g and b
    ///     components.  A positive shift pushes to saturation (255);
    ///     a negative shift pushes toward 0 (black).
    /// (2) The effect can be imagined using a color wheel that consists
    ///     (for our purposes) of these 6 colors, separated by 60 degrees:
    ///        red, magenta, blue, cyan, green, yellow
    /// (3) So, for example, a negative shift of the blue component
    ///     (bfract &lt; 0) could be accompanied by positive shifts
    ///     of red and green to make an image more yellow.
    /// (4) Examples of limiting cases:
    ///       rfract = 1 ==&gt; r = 255
    ///       rfract = -1 ==&gt; r = 0
    /// </remarks>
    public static Pix ColorShiftRGB(Pix pixs, float rfract, float gfract, float bfract)
    {
        const string func = "pixColorShiftRGB";

        if (pixs.Depth != 32)
            throw Lept.Arg(func, "pixs not 32 bpp");
        if (rfract < -1.0 || rfract > 1.0)
            throw Lept.Arg(func, "rfract not in [-1.0, 1.0]");
        if (gfract < -1.0 || gfract > 1.0)
            throw Lept.Arg(func, "gfract not in [-1.0, 1.0]");
        if (bfract < -1.0 || bfract > 1.0)
            throw Lept.Arg(func, "bfract not in [-1.0, 1.0]");
        if (rfract == 0.0 && gfract == 0.0 && bfract == 0.0)
            return Copy(null, pixs);

        int[] rlut = new int[256];
        int[] glut = new int[256];
        int[] blut = new int[256];
        for (int i = 0; i < 256; i++) {
            float fi = i;
            if (rfract >= 0) {
                rlut[i] = (int)(fi + (255.0 - fi) * rfract);
            } else {
                rlut[i] = (int)(fi * (1.0 + rfract));
            }
            if (gfract >= 0) {
                glut[i] = (int)(fi + (255.0 - fi) * gfract);
            } else {
                glut[i] = (int)(fi * (1.0 + gfract));
            }
            if (bfract >= 0) {
                blut[i] = (int)(fi + (255.0 - fi) * bfract);
            } else {
                blut[i] = (int)(fi * (1.0 + bfract));
            }
        }

        pixs.GetDimensions(out int w, out int h, out _);
        uint[] datas = pixs.Data;
        int wpls = pixs.Wpl;
        Pix pixd = Create(w, h, 32);
        uint[] datad = pixd.Data;
        int wpld = pixd.Wpl;
        for (int i = 0; i < h; i++) {
            int lines = i * wpls;
            int lined = i * wpld;
            for (int j = 0; j < w; j++) {
                ExtractRGBValues(datas[lines + j], out int rval, out int gval, out int bval);
                ComposeRGBPixel(rlut[rval], glut[gval], blut[bval], out datad[lined + j]);
            }
        }

        return pixd;
    }

    /*-----------------------------------------------------------------------*
     *                     Darken gray (unsaturated) pixels
     *-----------------------------------------------------------------------*/
    // leptonica: pixDarkenGray (enhance.c)
    /// <summary>Darkens the gray (unsaturated) pixels of a 32 bpp rgb image.</summary>
    /// <param name="pixd">[optional] can be null or equal to pixs</param>
    /// <param name="pixs">32 bpp rgb</param>
    /// <param name="thresh">pixels with max component &gt;= %thresh are unchanged</param>
    /// <param name="satlimit">pixels with saturation &gt;= %satlimit are unchanged</param>
    /// <remarks>
    /// (1) This darkens gray pixels, by a fraction (sat/%satlimit), where
    ///     the saturation, sat, is the component difference (max - min).
    ///     The pixel value is unchanged if sat &gt;= %satlimit.  A typical
    ///     value of %satlimit might be 40; the larger the value, the
    ///     more that pixels with a smaller saturation will be darkened.
    /// (2) Pixels with max component &gt;= %thresh are unchanged. This can be
    ///     used to prevent bright pixels with low saturation from being
    ///     darkened.  Setting thresh == 0 is a no-op; setting %thresh == 255
    ///     causes the darkening to be applied to all pixels.
    /// (3) This function is useful to enhance pixels relative to a
    ///     gray background.
    /// (4) A related function that builds a 1 bpp mask over the gray
    ///     pixels is pixMaskOverGrayPixels().
    /// </remarks>
    public static Pix DarkenGray(Pix? pixd, Pix pixs, int thresh, int satlimit)
    {
        const string func = "pixDarkenGray";

        if (pixs.Depth != 32)
            throw Lept.Arg(func, "pixs undefined or not 32 bpp");
        if (thresh < 0 || thresh > 255)
            throw Lept.Arg(func, "invalid thresh");
        if (satlimit < 1)
            throw Lept.Arg(func, "invalid satlimit");
        if (pixd != null && pixs != pixd)
            throw Lept.Arg(func, "not new or in-place");

        pixs.GetDimensions(out int w, out int h, out _);
        uint[] datas = pixs.Data;
        int wpls = pixs.Wpl;
        pixd = Copy(pixd, pixs);
        uint[] datad = pixd.Data;
        int wpld = pixd.Wpl;

        for (int i = 0; i < h; i++) {
            int lines = i * wpls;
            int lined = i * wpld;
            for (int j = 0; j < w; j++) {
                ExtractRGBValues(datas[lines + j], out int rval, out int gval, out int bval);
                int minrg = Math.Min(rval, gval);
                int min = Math.Min(minrg, bval);
                int maxrg = Math.Max(rval, gval);
                int max = Math.Max(maxrg, bval);
                int sat = max - min;
                if (max >= thresh || sat >= satlimit)
                    continue;
                float ratio = (float)sat / (float)satlimit;
                ComposeRGBPixel((int)(ratio * rval), (int)(ratio * gval),
                                (int)(ratio * bval), out datad[lined + j]);
            }
        }
        return pixd;
    }

    /*-----------------------------------------------------------------------*
     *            General multiplicative constant color transform            *
     *-----------------------------------------------------------------------*/
    // leptonica: pixMultConstantColor (enhance.c)
    /// <summary>Multiplies the colors of a colormapped or rgb image by constant factors.</summary>
    /// <param name="rfact">red multiplicative factor</param>
    /// <param name="gfact">green multiplicative factor</param>
    /// <param name="bfact">blue multiplicative factor</param>
    /// <returns>pixd colormapped or rgb, with colors scaled</returns>
    /// <remarks>
    /// (1) rfact, gfact and bfact can only have non-negative values.
    ///     They can be greater than 1.0.  All transformed component
    ///     values are clipped to the interval [0, 255].
    /// (2) For multiplication with a general 3x3 matrix of constants,
    ///     use pixMultMatrixColor().
    /// </remarks>
    public Pix MultConstantColor(float rfact, float gfact, float bfact)
    {
        const string func = "pixMultConstantColor";

        GetDimensions(out int w, out int h, out int d);
        PixColormap? cmap = Colormap;
        if (cmap == null && d != 32)
            throw Lept.Arg(func, "pixs not cmapped or 32 bpp");
        rfact = (float)Math.Max(0.0, rfact);
        gfact = (float)Math.Max(0.0, gfact);
        bfact = (float)Math.Max(0.0, bfact);

        int nrval, ngval, nbval;
        if (cmap != null) {
            Pix pixcm = Copy(null, this);
            cmap = pixcm.Colormap!;
            int ncolors = cmap.Count;
            for (int i = 0; i < ncolors; i++) {
                cmap.GetColor(i, out int rval, out int gval, out int bval);
                nrval = (int)(rfact * rval);
                ngval = (int)(gfact * gval);
                nbval = (int)(bfact * bval);
                nrval = Math.Min(255, nrval);
                ngval = Math.Min(255, ngval);
                nbval = Math.Min(255, nbval);
                cmap.ResetColor(i, nrval, ngval, nbval);
            }
            return pixcm;
        }

        Pix pixd = CreateTemplateNoInit(this);
        uint[] datas = Data;
        uint[] datad = pixd.Data;
        int wpls = Wpl;
        int wpld = pixd.Wpl;
        Span<uint> rTab = stackalloc uint[256];
        Span<uint> gTab = stackalloc uint[256];
        Span<uint> bTab = stackalloc uint[256];
        for (int k = 0; k < 256; k++) {
            rTab[k] = (uint)Math.Min(255, (int)(rfact * k)) << L_RED_SHIFT;
            gTab[k] = (uint)Math.Min(255, (int)(gfact * k)) << L_GREEN_SHIFT;
            bTab[k] = (uint)Math.Min(255, (int)(bfact * k)) << L_BLUE_SHIFT;
        }
        ref uint rRef = ref MemoryMarshal.GetReference(rTab);
        ref uint gRef = ref MemoryMarshal.GetReference(gTab);
        ref uint bRef = ref MemoryMarshal.GetReference(bTab);
        ref uint baseS = ref MemoryMarshal.GetArrayDataReference(datas);
        ref uint baseD = ref MemoryMarshal.GetArrayDataReference(datad);
        for (int i = 0; i < h; i++) {
            ref uint rs = ref Unsafe.Add(ref baseS, (nuint)(i * wpls));
            ref uint rd = ref Unsafe.Add(ref baseD, (nuint)(i * wpld));
            for (int j = 0; j < w; j++) {
                uint px = Unsafe.Add(ref rs, (nuint)j);
                Unsafe.Add(ref rd, (nuint)j) =
                    Unsafe.Add(ref rRef, (nuint)((px >> L_RED_SHIFT) & 0xff)) |
                    Unsafe.Add(ref gRef, (nuint)((px >> L_GREEN_SHIFT) & 0xff)) |
                    Unsafe.Add(ref bRef, (nuint)((px >> L_BLUE_SHIFT) & 0xff));
            }
        }

        return pixd;
    }

    // leptonica: pixMultMatrixColor (enhance.c)
    /// <summary>Transforms the colors of a colormapped or rgb image by a 3x3 matrix.</summary>
    /// <param name="kel">kernel 3x3 matrix of floats</param>
    /// <returns>pixd colormapped or rgb</returns>
    /// <remarks>
    /// (1) The kernel is a data structure used mostly for floating point
    ///     convolution.  Here it is a 3x3 matrix of floats that are used
    ///     to transform the pixel values by matrix multiplication:
    ///       nrval = a[0,0] * rval + a[0,1] * gval + a[0,2] * bval
    ///       ngval = a[1,0] * rval + a[1,1] * gval + a[1,2] * bval
    ///       nbval = a[2,0] * rval + a[2,1] * gval + a[2,2] * bval
    /// (2) The matrix can be generated in several ways.
    ///     See kernel.c for details.  Here are two of them:
    ///       (a) kel = kernelCreate(3, 3);
    ///           kernelSetElement(kel, 0, 0, val00);
    ///           kernelSetElement(kel, 0, 1, val01);
    ///           ...
    ///       (b) from a static string; e.g.,:
    ///           const char *kdata = " 0.6  0.3 -0.2 "
    ///                               " 0.1  1.2  0.4 "
    ///                               " -0.4 0.2  0.9 ";
    ///           kel = kernelCreateFromString(3, 3, 0, 0, kdata);
    /// (3) For the special case where the matrix is diagonal, it is easier
    ///     to use pixMultConstantColor().
    /// (4) Matrix entries can have positive and negative values, and can
    ///     be larger than 1.0.  All transformed component values
    ///     are clipped to [0, 255].
    /// </remarks>
    public Pix MultMatrixColor(L_Kernel kel)
    {
        const string func = "pixMultMatrixColor";

        kel.GetParameters(out int kh, out int kw, out _, out _);
        if (kw != 3 || kh != 3)
            throw Lept.Arg(func, "matrix not 3x3");
        GetDimensions(out int w, out int h, out int d);
        PixColormap? cmap = Colormap;
        if (cmap == null && d != 32)
            throw Lept.Arg(func, "pixs not cmapped or 32 bpp");

        float[] v = new float[9];  /* use linear array for convenience */
        int index = 0;
        for (int i = 0; i < 3; i++)
            for (int j = 0; j < 3; j++, index++)
                v[index] = kel.GetElement(i, j);

        int nrval, ngval, nbval;
        if (cmap != null) {
            Pix pixcm = Copy(null, this);
            cmap = pixcm.Colormap!;
            int ncolors = cmap.Count;
            for (int i = 0; i < ncolors; i++) {
                cmap.GetColor(i, out int rval, out int gval, out int bval);
                nrval = (int)(v[0] * rval + v[1] * gval + v[2] * bval);
                ngval = (int)(v[3] * rval + v[4] * gval + v[5] * bval);
                nbval = (int)(v[6] * rval + v[7] * gval + v[8] * bval);
                nrval = Math.Max(0, Math.Min(255, nrval));
                ngval = Math.Max(0, Math.Min(255, ngval));
                nbval = Math.Max(0, Math.Min(255, nbval));
                cmap.ResetColor(i, nrval, ngval, nbval);
            }
            return pixcm;
        }

        Pix pixd = CreateTemplateNoInit(this);
        uint[] datas = Data;
        uint[] datad = pixd.Data;
        int wpls = Wpl;
        int wpld = pixd.Wpl;
        float v0 = v[0], v1 = v[1], v2 = v[2];
        float v3 = v[3], v4 = v[4], v5 = v[5];
        float v6 = v[6], v7 = v[7], v8 = v[8];
        LeptParallel.ForRows(h, (long)w * 12L, (yStart, yEnd) => {
            ref uint baseS = ref MemoryMarshal.GetArrayDataReference(datas);
            ref uint baseD = ref MemoryMarshal.GetArrayDataReference(datad);
            for (int i = yStart; i < yEnd; i++) {
                ref uint rs = ref Unsafe.Add(ref baseS, (nuint)(i * wpls));
                ref uint rd = ref Unsafe.Add(ref baseD, (nuint)(i * wpld));
                for (int j = 0; j < w; j++) {
                    uint px = Unsafe.Add(ref rs, (nuint)j);
                    int rval = (int)((px >> L_RED_SHIFT) & 0xff);
                    int gval = (int)((px >> L_GREEN_SHIFT) & 0xff);
                    int bval = (int)((px >> L_BLUE_SHIFT) & 0xff);
                    int nr = Math.Clamp((int)(v0 * rval + v1 * gval + v2 * bval), 0, 255);
                    int ng = Math.Clamp((int)(v3 * rval + v4 * gval + v5 * bval), 0, 255);
                    int nb = Math.Clamp((int)(v6 * rval + v7 * gval + v8 * bval), 0, 255);
                    Unsafe.Add(ref rd, (nuint)j) = ((uint)nr << L_RED_SHIFT) | ((uint)ng << L_GREEN_SHIFT) | ((uint)nb << L_BLUE_SHIFT);
                }
            }
        });

        return pixd;
    }

    /*-------------------------------------------------------------*
     *                    Half-edge by bandpass                    *
     *-------------------------------------------------------------*/
    // leptonica: pixHalfEdgeByBandpass (enhance.c)
    /// <summary>Computes a half-edge image as the difference of two lowpass filtered images.</summary>
    /// <param name="sm1h">"half-width" of smoothing filter sm1, horizontal</param>
    /// <param name="sm1v">"half-width" of smoothing filter sm1, vertical</param>
    /// <param name="sm2h">"half-width" of smoothing filter sm2, horizontal</param>
    /// <param name="sm2v">"half-width" of smoothing filter sm2, vertical; require sm2 != sm1</param>
    /// <remarks>
    /// (1) We use symmetric smoothing filters of odd dimension,
    ///     typically use 3, 5, 7, etc.  The smoothing parameters
    ///     for these are 1, 2, 3, etc.  The filter size is related
    ///     to the smoothing parameter by
    ///          size = 2 * smoothing + 1
    /// (2) Because we take the difference of two lowpass filters,
    ///     this is actually a bandpass filter.
    /// (3) We allow both filters to be anisotropic.
    /// (4) Consider either the h or v component of the 2 filters.
    ///     Depending on whether sm1 &gt; sm2 or sm2 &gt; sm1, we get
    ///     different halves of the smoothed gradients (or "edges").
    ///     This difference of smoothed signals looks more like
    ///     a second derivative of a transition, which we rectify
    ///     by not allowing the signal to go below zero.  If sm1 &lt; sm2,
    ///     the sm2 transition is broader, so the difference between
    ///     sm1 and sm2 signals is positive on the upper half of
    ///     the transition.  Likewise, if sm1 &gt; sm2, the sm1 - sm2
    ///     signal difference is positive on the lower half of
    ///     the transition.
    /// </remarks>
    public Pix HalfEdgeByBandpass(int sm1h, int sm1v, int sm2h, int sm2v)
    {
        const string func = "pixHalfEdgeByBandpass";

        if (sm1h == sm2h && sm1v == sm2v)
            throw Lept.Arg(func, "sm2 = sm1");
        int d = Depth;
        if (d != 8 && d != 32)
            throw Lept.Arg(func, "pixs not 8 or 32 bpp");
        Pix pixg;
        if (d == 32)
            pixg = ConvertRGBToLuminance();
        else   /* d == 8 */
            pixg = Clone(this);

        /* Make a convolution accumulator and use it twice */
        Pix pixacc = pixg.BlockconvAccum();
        Pix pixc1 = pixg.BlockconvGray(pixacc, sm1h, sm1v);
        Pix pixc2 = pixg.BlockconvGray(pixacc, sm2h, sm2v);

        /* Compute the half-edge using pixc1 - pixc2.  */
        SubtractGray(pixc1, pixc1, pixc2);
        return pixc1;
    }
}

public sealed partial class Numa
